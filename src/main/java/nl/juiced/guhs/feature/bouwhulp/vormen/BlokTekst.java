    /** The text in blocks: x along the text, y up, z the depth. Unknown characters become a space. */
    public static Map<BlockPos, BlockState> maak(String tekst, int hoogte, int diepte, Mix mat) {
        String t = tekst.replace("<3", "♥").toUpperCase(Locale.ROOT);
        int s = Math.max(1, hoogte / 7);
        Map<BlockPos, BlockState> uit = new LinkedHashMap<>();
        int x0 = 0;
        for (char c : t.toCharArray()) {
            String[] g = LETTERS.getOrDefault(c, LETTERS.get(' '));
            for (int r = 0; r < 7; r++) {
                for (int k = 0; k < 5; k++) {
                    if (g[r].charAt(k) != '#') {
                        continue;
                    }
                    for (int a = 0; a < s; a++) {
                        for (int b = 0; b < s; b++) {
                            for (int z = 0; z < Math.max(1, diepte); z++) {
                                BlockPos p = new BlockPos(x0 + k * s + a, (6 - r) * s + b, z);
                                uit.put(p, Vormen.staat(mat.kies(p, Blocks.PINK_CONCRETE)));
                            }
                        }
                    }
                }
            }
            x0 += 6 * s;
        }
        return uit;
    }

    /** How wide a text gets at this height. */
    public static int breedte(String tekst, int hoogte) {
        return tekst.replace("<3", "♥").length() * 6 * Math.max(1, hoogte / 7);
    }

