/**
 * (S-SITE) The runtime half of the guhs.nl/vadsrijk wiki data: dumps the registries the offline export (tools/wiki_site/vadsrijk/
 * export.py) cannot read from the repo files reliably: areas with level ranges, spawners (type, levels, element, elite chance),
 * boss arenas (respawn), every loot base type with its stats per level, the loot tables, rarities, classes, pets, mounts and the
 * NPC/POI positions as the game resolves them. The site build merges this file ({@code docs/wiki/vadsrijk_runtime.json}) when it
 * exists. Only static game content: never player data.
 * <p>Make it: {@code runGameTestServer -Pgt=VadsrijkWeb} (writes {@code vadsrijk_runtime.json} in the run dir, or the path in the
 * system property {@code guhs.wikiexport}), or in game {@code /guhs vadsrijk web wikiexport} (op) -> {@code <server>/vadsrijk_runtime.json}.
 */
public final class WikiExport {
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();
    /** The levels the base-type stats are sampled at (the site interpolates nothing; it shows these). */
    private static final int[] LEVELS = {1, 10, 20, 30, 40, 50};

    private WikiExport() {
    }

    public static JsonObject bouw() {
        JsonObject o = new JsonObject();
        o.addProperty("_", "generated by WikiExport (S-SITE); static game content only");
        o.add("gebieden", gebieden());
        o.add("spawners", spawners());
        o.add("arenas", arenas());
        o.add("basistypes", basistypes());
        o.add("loottabellen", loottabellen());
        o.add("zeldzaamheden", zeldzaamheden());
        o.add("klassen", klassen());
        o.add("huisdieren", huisdieren());
        o.add("rijdieren", rijdieren());
        o.add("npcs", npcs());
        o.add("sets", sets());
        o.add("kristallen", kristallen());
        o.add("sterren", sterren());
        return o;
    }

    public static Path schrijf(Path pad) throws IOException {
        Path tmp = pad.resolveSibling(pad.getFileName() + ".tmp");
        if (pad.getParent() != null) {
            Files.createDirectories(pad.getParent());
        }
        Files.writeString(tmp, GSON.toJson(bouw()), StandardCharsets.UTF_8);
        Files.move(tmp, pad, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
        return pad;
    }

    static JsonArray pos(BlockPos p) {
        JsonArray a = new JsonArray();
        a.add(p.getX());
        a.add(p.getY());
        a.add(p.getZ());
        return a;
    }

    private static JsonObject stats(Stats s) {
        JsonObject o = new JsonObject();
        for (Map.Entry<Stat, Double> e : s.alles().entrySet()) {
            if (e.getValue() != 0) {
                o.addProperty(e.getKey().name().toLowerCase(), Math.round(e.getValue() * 100) / 100.0);
            }
        }
        return o;
    }

    private static JsonArray gebieden() {
        JsonArray a = new JsonArray();
        for (Gebieden.Gebied g : Gebieden.alle()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", g.id());
            JsonArray box = new JsonArray();
            box.add(g.minX());
            box.add(g.minZ());
            box.add(g.maxX());
            box.add(g.maxZ());
            o.add("doos", box);
            o.addProperty("min_lv", g.minLevel());
            o.addProperty("max_lv", g.maxLevel());
            o.addProperty("stad", g.stad());
            if (g.laag() != null) {
                Gebieden.Laag l = g.laag();
                JsonObject lo = new JsonObject();
                lo.addProperty("min_y", Math.max(l.minY(), -64));
                lo.addProperty("max_y", Math.min(l.maxY(), 400));
                if (l.rMax() > 0) {
                    lo.addProperty("cx", l.cx());
                    lo.addProperty("cz", l.cz());
                    lo.addProperty("r_min", l.rMin());
                    lo.addProperty("r_max", l.rMax());
                }
                o.add("laag", lo);
            }
            a.add(o);
        }
        return a;
    }

    private static JsonArray spawners() {
        JsonArray a = new JsonArray();
        for (Spawners.Spawner s : Spawners.alle()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", s.id());
            String type;
            try {
                EntityType<?> t = s.type().get();
                type = String.valueOf(BuiltInRegistries.ENTITY_TYPE.getKey(t));
            } catch (RuntimeException e) {
                type = "?";
            }
            o.addProperty("type", type);
            o.add("centrum", pos(s.centrum()));
            o.addProperty("straal", s.straal());
            o.addProperty("max", s.max());
            o.addProperty("respawn_s", s.respawnTicks() / 20);
            o.addProperty("min_lv", s.minLevel());
            o.addProperty("max_lv", s.maxLevel());
            o.addProperty("element", s.element() == null ? "geen" : s.element().name().toLowerCase());
            o.addProperty("elite_kans", s.eliteKans());
            o.addProperty("grot", s.grot());
            a.add(o);
        }
        return a;
    }

    private static JsonArray arenas() {
        JsonArray a = new JsonArray();
        for (String id : Arenas.ids()) {
            Arena r = Arenas.van(id);
            if (r == null) {
                continue;
            }
            JsonObject o = new JsonObject();
            o.addProperty("id", id);
            o.add("centrum", pos(r.centrum()));
            o.addProperty("straal", r.straal());
            o.add("deur", pos(r.deur()));
            o.addProperty("respawn_s", r.respawnSeconden());
            o.addProperty("titel_key", r.titelKey());
            a.add(o);
        }
        return a;
    }

    private static JsonArray basistypes() {
        JsonArray a = new JsonArray();
        for (BasisType t : BasisTypes.alle()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", t.id());
            o.addProperty("item", t.itemId());
            o.addProperty("slot", t.slot() == null ? "?" : t.slot().name().toLowerCase());
            o.addProperty("soort", t.soort());
            o.addProperty("klasse", t.klasse());
            o.addProperty("element", t.element() == null ? "geen" : t.element().name().toLowerCase());
            o.addProperty("flavours", t.flavours());
            JsonObject per = new JsonObject();
            for (int lv : LEVELS) {
                JsonObject l = stats(t.statsOp(lv));
                if (t.schade() != 0 || t.schadePerLevel() != 0) {
                    l.addProperty("schade", Math.round(t.schadeOp(lv) * 100) / 100.0);
                }
                per.add(String.valueOf(lv), l);
            }
            o.add("per_level", per);
            a.add(o);
        }
        return a;
    }

    private static JsonObject loottabellen() {
        JsonObject o = new JsonObject();
        for (Map.Entry<String, LootTabel> e : LootTabellen.alle().entrySet()) {
            LootTabel t = e.getValue();
            JsonObject j = new JsonObject();
            j.addProperty("rollen", t.rollen());
            j.addProperty("kans", t.kans());
            j.addProperty("geluk", t.geluk());
            j.addProperty("munten_min", t.muntenMin());
            j.addProperty("munten_max", t.muntenMax());
            JsonObject regels = new JsonObject();
            Map<String, Integer> som = new LinkedHashMap<>();
            for (LootTabel.Regel r : t.regels()) {
                som.merge(r.basisType(), r.gewicht(), Integer::sum);
            }
            som.forEach(regels::addProperty);
            j.add("regels", regels);
            o.add(e.getKey(), j);
        }
        return o;
    }

    private static JsonArray zeldzaamheden() {
        JsonArray a = new JsonArray();
        for (Zeldzaamheid z : Zeldzaamheid.values()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", z.name().toLowerCase());
            o.addProperty("kleur", String.format("#%06X", z.rgb));
            o.addProperty("min_bonus", z.minBonus);
            o.addProperty("max_bonus", z.maxBonus);
            o.addProperty("factor", z.factor);
            o.addProperty("gewicht", z.gewicht);
            a.add(o);
        }
        return a;
    }

    private static JsonArray klassen() {
        JsonArray a = new JsonArray();
        for (Klasse k : Klassen.alle()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", k.id());
            o.addProperty("naam_key", k.naamKey());
            JsonArray w = new JsonArray();
            k.wapenSoorten().forEach(w::add);
            o.add("wapens", w);
            JsonObject per = new JsonObject();
            for (int lv : LEVELS) {
                per.add(String.valueOf(lv), stats(k.basis(lv)));
            }
            o.add("per_level", per);
            a.add(o);
        }
        return a;
    }

    private static JsonArray huisdieren() {
        JsonArray a = new JsonArray();
        for (Huisdier h : Huisdieren.alle()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", h.id());
            o.addProperty("baas", h.baas());
            o.addProperty("naam_key", h.naamKey());
            a.add(o);
        }
        return a;
    }

    private static JsonArray rijdieren() {
        JsonArray a = new JsonArray();
        for (RijdierSoort r : RijdierSoort.values()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", r.id());
            o.addProperty("naam_key", r.naamKey());
            o.addProperty("bron", r.bron);
            o.addProperty("prijs", r.prijs);
            o.addProperty("zweeft", r.zweeft());
            o.addProperty("kleuren", r.kleuren());
            o.addProperty("snelheid_1", Math.round(r.snelheid(1) * 1000) / 1000.0);
            o.addProperty("snelheid_max", Math.round(r.snelheid(RijdierSoort.MAX_LEVEL) * 1000) / 1000.0);
            a.add(o);
        }
        return a;
    }

    private static JsonObject npcs() {
        JsonObject o = new JsonObject();
        JsonObject plek = new JsonObject();
        Npcs.alle().forEach(d -> plek.add(d.id(), pos(d.plek())));
        NpcPlekken.NPC.forEach((k, v) -> { if (!plek.has(k)) plek.add(k, pos(v)); });
        Z2NpcPlekken.NPC.forEach((k, v) -> { if (!plek.has(k)) plek.add(k, pos(v)); });
        Z3NpcPlekken.NPC.forEach((k, v) -> { if (!plek.has(k)) plek.add(k, pos(v)); });
        o.add("plek", plek);
        JsonObject poi = new JsonObject();
        NpcPlekken.POI.forEach((k, v) -> poi.add(k, pos(v)));
        Z2NpcPlekken.POI.forEach((k, v) -> poi.add(k, pos(v)));
        Z3NpcPlekken.POI.forEach((k, v) -> poi.add(k, pos(v)));
        o.add("poi", poi);
        JsonObject rol = new JsonObject();
        Npcs.alle().forEach(d -> { if (d.rol() != null) rol.addProperty(d.id(), d.rol()); });
        o.add("rol", rol);
        return o;
    }

    private static JsonObject sets() {
        JsonObject o = new JsonObject();
        Map<String, java.util.List<String>> m = new LinkedHashMap<>();
        m.put("klodder", nl.juiced.guhs.feature.vadsrijk.wezens.loot.SetBonussen.KLODDERSET);
        m.put("zwam", nl.juiced.guhs.feature.vadsrijk.wezens.loot.SetBonussen.ZWAMSET);
        m.put("kristal", nl.juiced.guhs.feature.vadsrijk.zone2.wezens.loot.Z2Sets.KRISTALSET);
        m.put("mika", nl.juiced.guhs.feature.vadsrijk.zone2.wezens.loot.Z2Sets.MIKASET);
        m.put("bloesem", nl.juiced.guhs.feature.vadsrijk.zone3.wezens.loot.Z3Loot.BLOESEM);
        m.put("schors", nl.juiced.guhs.feature.vadsrijk.zone3.wezens.loot.Z3Loot.SCHORS);
        m.put("wortel", nl.juiced.guhs.feature.vadsrijk.zone3.wezens.loot.Z3Loot.WORTEL);
        m.forEach((k, v) -> {
            JsonArray a = new JsonArray();
            v.forEach(a::add);
            o.add(k, a);
        });
        return o;
    }

    private static JsonArray kristallen() {
        JsonArray a = new JsonArray();
        for (nl.juiced.guhs.feature.vadsrijk.zone2.systemen.Kristallen.Soort k : nl.juiced.guhs.feature.vadsrijk.zone2.systemen.Kristallen.SOORTEN.values()) {
            JsonObject o = new JsonObject();
            o.addProperty("id", k.id());
            o.addProperty("item", "guhs:" + k.itemId());
            o.addProperty("stat", k.stat() == null ? "bevriezen" : k.stat().name().toLowerCase());
            JsonArray w = new JsonArray();
            for (int q = 0; q < 3; q++) {
                w.add(Math.round(k.waarde(q) * 100) / 100.0);
            }
            o.add("waarde", w);
            o.addProperty("kleur", String.format("#%06X", k.kleur()));
            a.add(o);
        }
        return a;
    }

    private static JsonObject sterren() {
        JsonObject o = new JsonObject();
        o.addProperty("max", nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.MAX);
        JsonArray rijen = new JsonArray();
        for (int s = 0; s < nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.MAX; s++) {
            JsonObject r = new JsonObject();
            r.addProperty("van", s);
            r.addProperty("kans", nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.KANS[s]);
            double[] risico = nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.risico(s);
            r.addProperty("kwijt", Math.round(risico[0] * 1000) / 1000.0);
            r.addProperty("verpluisd", Math.round(risico[1] * 1000) / 1000.0);
            r.addProperty("steentjes", nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.steentjes(s));
            r.addProperty("prijs_lv10", nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.prijs(10, s));
            r.addProperty("prijs_lv30", nl.juiced.guhs.feature.vadsrijk.economie.SterRegels.prijs(30, s));
            rijen.add(r);
        }
        o.add("rijen", rijen);
        return o;
    }

    /** For the gametest: non-empty sections. */
    static String controleer(JsonObject o) {
        for (String k : new String[] {"gebieden", "spawners", "basistypes", "klassen", "rijdieren"}) {
            if (!o.has(k) || o.getAsJsonArray(k).isEmpty()) {
                return "section " + k + " is empty";
            }
        }
        if (o.getAsJsonObject("loottabellen").isEmpty()) {
            return "no loot tables";
        }
        return null;
    }
}
