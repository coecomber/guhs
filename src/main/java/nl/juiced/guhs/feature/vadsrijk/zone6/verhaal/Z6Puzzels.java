/**
 * The puzzles of the Zijdeland, all on the Vadsrijk talking screen ({@link Praat}): a puzzle is a row of steps, each a question
 * with a few answers of which one is right. A wrong answer explains (gently) and starts the puzzle again; the last right answer
 * counts {@code meld("z6_puzzel", id)}. Data: data/guhs/vadsrijk/z6verhaal/puzzels.json (generated by
 * tools/features/vadsrijk_u_z6verhaal.py: per puzzle the number of options per step and the right one), texts
 * {@code vadsrijk.z6verhaal.puzzel.<id>.*}.
 * <ul>
 *   <li><b>Star puzzles</b> (the five beacons, the tutorial at Twinkel's telescope, the exam): follow the stars of a constellation in
 *       the order the hint describes. At a beacon the last star lights it: {@link #steekAan} (the vision of Moeder Bron, the lens
 *       catches a shard). In daylight the Sterrenlens shows the night sky (a short Darkness + star particles): no waiting for night.</li>
 *   <li><b>The cave song</b> (Zingende Zoutgrot) and the <b>haggling</b> (Afdingen!) use the same engine.</li>
 * </ul>
 * The lit beacons are per player in {@code extra("npc").z6_bakens} (id -> true).
 */
public final class Z6Puzzels {
    private static final Logger LOG = LogUtils.getLogger();
    public static final String BESTAND = "/data/guhs/vadsrijk/z6verhaal/puzzels.json";
    public static final String BAKENS = "z6_bakens";
    static final String SLEUTEL = "vr_z6_puzzel";
    static final int STOP = 99;
    static final String Z = Z6Verhaal.Z;

    /** One puzzle: per step the number of options and the right one. */
    public record Puzzel(String id, int[] opties, int[] goed) {
        int stappen() {
            return goed.length;
        }
    }

    private static volatile boolean geladen;
    static final Map<String, Puzzel> PUZZELS = new LinkedHashMap<>();
    /** Beacon id -> its puzzle (the order of the story: palm, zout, ruine, duin, oase). */
    static final Map<String, String> BAKEN_PUZZEL = new LinkedHashMap<>();

    /** The open puzzle of a player: which, the step, the beacon it lights (or ""), the NPC talking (or -1). */
    private record Open(String id, int stap, String baken, int entity) {
    }

    private static final Map<UUID, Open> OPEN = new ConcurrentHashMap<>();

    private Z6Puzzels() {
    }

    static synchronized void init() {
        laad();
        Praat.luister(SLEUTEL, Z6Puzzels::antwoord);
    }

    static synchronized void laad() {
        if (geladen) {
            return;
        }
        geladen = true;
        try (InputStream in = Z6Puzzels.class.getResourceAsStream(BESTAND)) {
            if (in == null) {
                LOG.error("Vadsrijk z6 verhaal: {} is missing", BESTAND);
                return;
            }
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("puzzels").entrySet()) {
                com.google.gson.JsonArray st = e.getValue().getAsJsonObject().getAsJsonArray("stappen");
                int[] o = new int[st.size()], g = new int[st.size()];
                for (int i = 0; i < st.size(); i++) {
                    o[i] = st.get(i).getAsJsonObject().get("opties").getAsInt();
                    g[i] = st.get(i).getAsJsonObject().get("goed").getAsInt();
                }
                PUZZELS.put(e.getKey(), new Puzzel(e.getKey(), o, g));
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("bakens").entrySet()) {
                BAKEN_PUZZEL.put(e.getKey(), e.getValue().getAsJsonObject().get("puzzel").getAsString());
            }
        } catch (Exception e) {
            LOG.error("Vadsrijk z6 verhaal: could not read {}", BESTAND, e);
        }
    }

    // ---- opening ---------------------------------------------------------------------------------------------------------------

    /** Opens a puzzle for this player (spreker: the NPC who talks, or null). At a beacon pass its id ("" otherwise). */
    public static void open(ServerPlayer p, String id, String baken, @Nullable Entity spreker) {
        laad();
        Puzzel pz = PUZZELS.get(id);
        if (pz == null) {
            return;
        }
        Open o = new Open(id, 0, baken, spreker == null ? -1 : spreker.getId());
        OPEN.put(p.getUUID(), o);
        List<Praat.Regel> r = new ArrayList<>();
        if (!baken.isEmpty() || id.startsWith("examen") || id.equals("oefen")) {
            nachtLens(p);
        }
        r.add(new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + ".intro"));
        r.add(new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + ".0.vraag"));
        Praat.scene(p, SLEUTEL, r, opties(pz, 0));
    }

    private static String naam(@Nullable Entity spreker, String id) {
        return spreker != null ? "" : Z + "puzzel." + id + ".titel";
    }

    private static Praat.Optie[] opties(Puzzel pz, int stap) {
        Praat.Optie[] o = new Praat.Optie[pz.opties()[stap] + 1];
        for (int i = 0; i < pz.opties()[stap]; i++) {
            o[i] = new Praat.Optie(i, Z + "puzzel." + pz.id() + "." + stap + "." + i);
        }
        o[o.length - 1] = new Praat.Optie(STOP, Z + "puzzel.optie.stop");
        return o;
    }

    /** In daylight the Sterrenlens shows the night sky for a moment: dark + stars round the player. */
    static void nachtLens(ServerPlayer p) {
        if (!(p.level() instanceof ServerLevel sl)) {
            return;
        }
        long t = nl.juiced.guhs.world.GuhTime.timeOfDay(sl);
        boolean dag = t < 12500 || t > 23500;
        if (dag) {
            p.addEffect(new MobEffectInstance(MobEffects.DARKNESS, 160, 0, false, false));
            p.sendSystemMessage(Component.translatable(Z + "puzzel.ster.lens").withStyle(ChatFormatting.DARK_AQUA, ChatFormatting.ITALIC));
        }
        sl.sendParticles(p, ParticleTypes.END_ROD, true, true, p.getX(), p.getY() + 12, p.getZ(), 60, 10, 4, 10, 0);
    }

    // ---- answers ---------------------------------------------------------------------------------------------------------------

    private static void antwoord(ServerPlayer p, @Nullable Entity spreker, int optie) {
        Open o = OPEN.get(p.getUUID());
        if (o == null) {
            return;
        }
        if (optie < 0 || optie == STOP) {
            OPEN.remove(p.getUUID());
            if (optie == STOP) {
                Praat.sluit(p);
            }
            return;
        }
        kies(p, spreker != null ? spreker : o.entity() < 0 ? null : p.level().getEntity(o.entity()), optie);
    }

    /** Choose answer k for the open puzzle (also the test path). False when no puzzle is open. */
    static boolean kies(ServerPlayer p, @Nullable Entity spreker, int k) {
        Open o = OPEN.get(p.getUUID());
        Puzzel pz = o == null ? null : PUZZELS.get(o.id());
        if (pz == null) {
            return false;
        }
        String id = pz.id();
        if (k != pz.goed()[o.stap()]) {
            // wrong: explain and start again
            OPEN.put(p.getUUID(), new Open(id, 0, o.baken(), o.entity()));
            Z6Verhaal.geluid(p, SoundEvents.NOTE_BLOCK_BASS.value(), 0.8f, 0.6f);
            Praat.scene(p, SLEUTEL, List.of(new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + ".fout"),
                    new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + ".0.vraag")), opties(pz, 0));
            return true;
        }
        int volgende = o.stap() + 1;
        Z6Verhaal.geluid(p, SoundEvents.AMETHYST_BLOCK_CHIME, 1f, 0.8f + 0.15f * volgende);
        if (p.level() instanceof ServerLevel sl) {
            sl.sendParticles(p, new DustParticleOptions(0xFFF0A0, 1.4f), true, true, p.getX(), p.getY() + 8 + volgende, p.getZ(), 20, 1.5, 0.5, 1.5, 0);
        }
        if (volgende < pz.stappen()) {
            OPEN.put(p.getUUID(), new Open(id, volgende, o.baken(), o.entity()));
            Praat.scene(p, SLEUTEL, List.of(new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + "." + volgende + ".vraag")),
                    opties(pz, volgende));
            return true;
        }
        // solved
        OPEN.remove(p.getUUID());
        Praat.scene(p, SLEUTEL, List.of(new Praat.Regel(spreker, naam(spreker, id), Z + "puzzel." + id + ".klaar")));
        Z6Verhaal.geluid(p, SoundEvents.PLAYER_LEVELUP, 0.8f, 1.4f);
        NpcApi.meld(p, "z6_puzzel", id);
        if (!o.baken().isEmpty()) {
            steekAan(p, o.baken());
        } else if (id.equals("oefen")) {
            Z6Verhaal.visioen(p, 0, Z6VerhaalPlekken.KIJKER);   // (the first whisper of Moeder Bron, in the water of Twinkel's basin)
        }
        return true;
    }

    /** (tests) Solve the open puzzle step by step with the right answers. */
    static boolean losOp(ServerPlayer p) {
        for (int i = 0; i < 12; i++) {
            Open o = OPEN.get(p.getUUID());
            if (o == null) {
                return i > 0;
            }
            kies(p, null, PUZZELS.get(o.id()).goed()[o.stap()]);
        }
        return !OPEN.containsKey(p.getUUID());
    }

    /** (tests) Is a puzzle open for this player (which)? */
    @Nullable
    static String open(ServerPlayer p) {
        Open o = OPEN.get(p.getUUID());
        return o == null ? null : o.id();
    }

    static void vergeet(ServerPlayer p) {
        OPEN.remove(p.getUUID());
        Questlog.data(p).remove(BAKENS);
    }

    // ---- the beacons --------------------------------------------------------------------------------------------------------------

    public static boolean brandt(ServerPlayer p, String baken) {
        return Questlog.map(p, BAKENS).getBooleanOr(baken, false);
    }

    /** How many of the five beacons burn for this player. */
    public static int aantal(ServerPlayer p) {
        CompoundTag m = Questlog.map(p, BAKENS);
        int n = 0;
        for (String b : Z6VerhaalPlekken.BAKEN.keySet()) {
            if (m.getBooleanOr(b, false)) {
                n++;
            }
        }
        return n;
    }

    /** A beacon is lit: the counter, the meld, a star shard in the lens, the light, and Moeder Bron's vision (stronger each time). */
    static void steekAan(ServerPlayer p, String baken) {
        CompoundTag m = Questlog.map(p, BAKENS);
        if (m.getBooleanOr(baken, false)) {
            NpcApi.meld(p, "z6_baken", baken);
            return;
        }
        m.putBoolean(baken, true);
        int n = aantal(p);
        NpcApi.meld(p, "z6_baken", baken);
        Questlog.geef(p, new ItemStack(Z6VerhaalRegistry.item("sterrenscherf")));
        p.sendSystemMessage(Component.translatable(Z + "baken.brandt", Component.translatable(Z + "bakens." + baken))
                .withStyle(ChatFormatting.GOLD, ChatFormatting.BOLD));
        BlockPos b = Z6VerhaalPlekken.BAKEN_STER.get(baken);
        if (b != null && p.level() instanceof ServerLevel sl) {
            Vec3 c = Vec3.atCenterOf(b);
            for (int y = 0; y < 60; y += 3) {
                sl.sendParticles(p, ParticleTypes.END_ROD, true, true, c.x, c.y + y, c.z, 4, 0.2, 1, 0.2, 0);
            }
            sl.sendParticles(p, ParticleTypes.FIREWORK, true, true, c.x, c.y + 4, c.z, 60, 1, 2, 1, 0.15);
        }
        p.level().playSound(null, p.blockPosition(), SoundEvents.BEACON_ACTIVATE, SoundSource.PLAYERS, 1f, 1.2f);
        if (n >= Z6VerhaalPlekken.BAKEN.size()) {
            GuhAdvancements.grant(p, "vr_z6_bakens_alle");
        }
        Z6Verhaal.visioen(p, n, b == null ? p.blockPosition() : b);
    }

    /** (dev/tests) Light a beacon without the puzzle. */
    static void zetBrandend(ServerPlayer p, String baken) {
        Questlog.map(p, BAKENS).putBoolean(baken, true);
    }

    /** The Sterrenlens (right click): how many beacons burn, which is next. */
    static void lens(ServerPlayer p) {
        int n = aantal(p);
        p.sendSystemMessage(Component.translatable(Z + "lens.stand", n).withStyle(ChatFormatting.GOLD));
        for (String b : Z6VerhaalPlekken.BAKEN.keySet()) {
            if (!brandt(p, b)) {
                p.sendSystemMessage(Component.translatable(Z + "lens.volgende", Component.translatable(Z + "bakens." + b)).withStyle(ChatFormatting.YELLOW));
                nachtLens(p);
                return;
            }
        }
        p.sendSystemMessage(Component.translatable(Z + "lens.alle").withStyle(ChatFormatting.LIGHT_PURPLE));
        nachtLens(p);
    }
}
