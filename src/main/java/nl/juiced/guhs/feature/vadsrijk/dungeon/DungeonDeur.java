/**
 * W-GROT (round W, user request "Caves hebben echt een dichte deur"): the closed door of every dungeon (caves first).
 * <ul>
 *   <li><b>The block</b> {@code guhs:vr_dungeondeur}: a full, solid, unbreakable block (no loot) with a theme per dungeon ({@link Thema})
 *       and a look ({@code deel}: 0 panel, 1 panel with the knocker, 2 a hatch). It never opens: you cannot walk in. Right-click
 *       (also with a weapon in your hand) = the dungeon interface ({@link DungeonRij#klikDeur}).</li>
 *   <li><b>Where</b>: {@link DungeonDeurData} (generated by tools/features/vadsrijk_w_grot.py from the cave plan + the tiles; the
 *       generator checks that the inside is not walkable from the stand spot with the door shut). Zone 6's door moves with
 *       u-z6wereld's POI "zoutgrot" ({@link Dungeon#pasAan}).</li>
 *   <li><b>Placing</b>: by the game, the first time a door's chunk is loaded this session (and again every 30 s while loaded, so a
 *       door never goes missing): only OPEN cells (air, water, plants) become door; nothing solid is ever replaced. No map regen.</li>
 * </ul>
 */
public final class DungeonDeur {
    public enum Thema implements StringRepresentable {
        ZWAM, KRISTAL, WORTEL, KORAAL, WOLK, ZOUT;

        @Override
        public String getSerializedName() {
            return name().toLowerCase(Locale.ROOT);
        }

        static Thema van(String s) {
            return valueOf(s.toUpperCase(Locale.ROOT));
        }
    }

    public static final EnumProperty<Thema> THEMA = EnumProperty.create("thema", Thema.class);
    public static final IntegerProperty DEEL = IntegerProperty.create("deel", 0, 2);

    public static final DeferredRegister.Blocks BLOCKS = DeferredRegister.createBlocks(Guhs.MODID);
    public static final DeferredBlock<Blok> BLOK = BLOCKS.registerBlock("vr_dungeondeur", Blok::new,
            () -> BlockBehaviour.Properties.ofFullCopy(Blocks.STRIPPED_SPRUCE_WOOD).strength(-1, 3600000).noLootTable());

    /** Gametests: doors standing in for a dungeon's real ones (dungeon id -> doors). */
    public static final Map<String, List<Deur>> TEST = new java.util.concurrent.ConcurrentHashMap<>();
    /** Doors placed this session (index in {@link #deuren()}) and when they were last checked. */
    private static final Set<Integer> GEZET = new HashSet<>();
    private static long laatsteRonde = -1;

    private DungeonDeur() {
    }

    /**
     * X-DUNGEON: the door's item, for creative / JEI / a builder's /give only (no recipe, no loot, the block is unbreakable: never
     * obtainable in survival). Placed by hand it is only a look: a click does nothing unless the cell is one of a dungeon's doors.
     */
    public static final DeferredRegister.Items ITEMS = DeferredRegister.createItems(Guhs.MODID);
    public static final net.neoforged.neoforge.registries.DeferredItem<DeurItem> ITEM = ITEMS.registerItem("vr_dungeondeur",
            p -> new DeurItem(BLOK.get(), p), () -> new net.minecraft.world.item.Item.Properties().rarity(net.minecraft.world.item.Rarity.EPIC));

    /** X-DUNGEON: the item's tooltip. */
    public static final class DeurItem extends net.minecraft.world.item.BlockItem {
        public DeurItem(Block b, net.minecraft.world.item.Item.Properties p) {
            super(b, p.useBlockDescriptionPrefix());
        }

        @Override
        public void appendHoverText(ItemStack stack, TooltipContext ctx, net.minecraft.world.item.component.TooltipDisplay display,
                java.util.function.Consumer<net.minecraft.network.chat.Component> t, net.minecraft.world.item.TooltipFlag flag) {
            t.accept(net.minecraft.network.chat.Component.translatable("block.guhs.vr_dungeondeur.tip").withStyle(net.minecraft.ChatFormatting.GRAY));
            t.accept(net.minecraft.network.chat.Component.translatable("block.guhs.vr_dungeondeur.tip2").withStyle(net.minecraft.ChatFormatting.DARK_GRAY));
        }
    }

    public static void register(IEventBus modBus) {
        BLOCKS.register(modBus);
        ITEMS.register(modBus);   // X-DUNGEON
        modBus.addListener((net.neoforged.neoforge.event.BuildCreativeModeTabContentsEvent e) -> {
            if (e.getTabKey() == nl.juiced.guhs.registry.ModCreativeTabs.GUHS_TAB.getKey()) {
                e.accept(new ItemStack(ITEM.get()));
            }
        });
    }

    public static void nieuweSessie() {
        GEZET.clear();
        laatsteRonde = -1;
    }

    /** The block. */
    public static final class Blok extends Block {
        public static final MapCodec<Blok> CODEC = simpleCodec(Blok::new);

        public Blok(BlockBehaviour.Properties p) {
            super(p);
            registerDefaultState(stateDefinition.any().setValue(THEMA, Thema.ZWAM).setValue(DEEL, 0));
        }

        @Override
        protected MapCodec<? extends Block> codec() {
            return CODEC;
        }

        @Override
        protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> b) {
            b.add(THEMA, DEEL);
        }

        @Override
        protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hit) {
            if (level instanceof ServerLevel sl && player instanceof ServerPlayer p) {
                DungeonRij.klikDeur(sl, pos, p);
            }
            return InteractionResult.SUCCESS;
        }

        @Override
        protected InteractionResult useItemOn(ItemStack stack, BlockState state, Level level, BlockPos pos, Player player, InteractionHand hand,
                BlockHitResult hit) {
            // (in the Vadsrijk you nearly always hold a weapon: that must not stop the door)
            if (level instanceof ServerLevel sl && player instanceof ServerPlayer p) {
                DungeonRij.klikDeur(sl, pos, p);
            }
            return InteractionResult.SUCCESS;
        }
    }

    // ---- the doors -------------------------------------------------------------------------------------------------------------

    /** Every door of the dungeons in this build (a door whose dungeon is not in the build is left out; {@link Dungeon#pasAan}). */
    public static List<Deur> deuren() {
        List<Deur> l = new ArrayList<>();
        for (Deur d : DungeonDeurData.ALLE) {
            Dungeon g = Dungeons.van(d.dungeon());
            if (g != null && !Dungeons.TEST.containsKey(d.dungeon())) {
                l.add(g.pasAan(d));
            }
        }
        return l;
    }

    /** A door moved by (dx, dy, dz) (for {@link Dungeon#pasAan}). */
    public static Deur verschoven(Deur d, int dx, int dy, int dz) {
        if (dx == 0 && dy == 0 && dz == 0) {
            return d;
        }
        List<int[]> c = new ArrayList<>();
        for (int[] a : d.cellen()) {
            c.add(new int[] {a[0] + dx, a[1] + dy, a[2] + dz, a[3]});
        }
        return new Deur(d.dungeon(), d.hoofd(), d.thema(), d.luik(), List.copyOf(c), d.voor().offset(dx, dy, dz), d.yawVoor(), d.binnen().offset(dx, dy, dz),
                d.yawBinnen(), d.zegel());
    }

    /** The doors of one dungeon (test doors first). */
    public static List<Deur> van(String dungeon) {
        List<Deur> t = TEST.get(dungeon);
        if (t != null) {
            return t;
        }
        List<Deur> l = new ArrayList<>();
        for (Deur d : deuren()) {
            if (d.dungeon().equals(dungeon)) {
                l.add(d);
            }
        }
        return l;
    }

    /** The main door of a dungeon (where you come out). */
    @Nullable
    public static Deur hoofd(String dungeon) {
        for (Deur d : van(dungeon)) {
            if (d.hoofd()) {
                return d;
            }
        }
        List<Deur> l = van(dungeon);
        return l.isEmpty() ? null : l.get(0);
    }

    /** The door that has this cell (null: none). */
    @Nullable
    public static Deur op(BlockPos pos) {
        for (List<Deur> l : TEST.values()) {
            for (Deur d : l) {
                if (heeft(d, pos)) {
                    return d;
                }
            }
        }
        for (Deur d : deuren()) {
            if (heeft(d, pos)) {
                return d;
            }
        }
        return null;
    }

    public static boolean heeft(Deur d, BlockPos pos) {
        for (int[] c : d.cellen()) {
            if (c[0] == pos.getX() && c[1] == pos.getY() && c[2] == pos.getZ()) {
                return true;
            }
        }
        return false;
    }

    /** The middle of a door (for distances, sounds). */
    public static BlockPos midden(Deur d) {
        long x = 0, y = 0, z = 0;
        for (int[] c : d.cellen()) {
            x += c[0];
            y += c[1];
            z += c[2];
        }
        int n = Math.max(1, d.cellen().size());
        return new BlockPos((int) Math.floorDiv(x, n), (int) Math.floorDiv(y, n), (int) Math.floorDiv(z, n));
    }

    /** Is the player on the INSIDE of this door (closer to "binnen" than to "voor"; under a hatch)? */
    public static boolean binnenKant(ServerPlayer p, Deur d) {
        return binnenKant(d, p.getX(), p.getY(), p.getZ());
    }

    /** The same for a position. */
    public static boolean binnenKant(Deur d, double x, double y, double z) {
        if (d.luik()) {
            return y < d.cellen().get(0)[1];
        }
        double a = sq(x - d.binnen().getX() - 0.5) + sq(y - d.binnen().getY()) + sq(z - d.binnen().getZ() - 0.5);
        double b = sq(x - d.voor().getX() - 0.5) + sq(y - d.voor().getY()) + sq(z - d.voor().getZ() - 0.5);
        return a < b;
    }

    private static double sq(double v) {
        return v * v;
    }

    // ---- placing ---------------------------------------------------------------------------------------------------------------

    /** Every 2 s: doors whose chunk is loaded and that were not placed this session (or 30 s ago) are (re)placed. */
    public static void tick(ServerLevel sl) {
        long nu = sl.getGameTime();
        if (nu % 40 != 0) {
            return;
        }
        boolean ronde = laatsteRonde < 0 || nu - laatsteRonde >= 600;
        if (ronde) {
            laatsteRonde = nu;
        }
        List<Deur> l = deuren();
        for (int i = 0; i < l.size(); i++) {
            Deur d = l.get(i);
            BlockPos m = midden(d);
            if (!sl.isLoaded(m)) {
                continue;
            }
            if (!GEZET.contains(i) || ronde) {
                plaats(sl, d);
                GEZET.add(i);
            }
            DungeonBord.zorg(sl, d, i);   // X-DUNGEON: the name board over the door (one per door, every 2 s)
        }
    }

    /** Places the door: open cells only (air, water, a plant); returns how many cells are door now. */
    public static int plaats(ServerLevel sl, Deur d) {
        int n = 0;
        Thema t = Thema.van(d.thema());
        for (int[] c : d.cellen()) {
            BlockPos p = new BlockPos(c[0], c[1], c[2]);
            BlockState s = sl.getBlockState(p);
            BlockState wil = BLOK.get().defaultBlockState().setValue(THEMA, t).setValue(DEEL, Math.max(0, Math.min(2, c[3])));
            if (s.is(BLOK.get())) {
                if (s != wil) {
                    sl.setBlock(p, wil, 2);
                }
                n++;
                continue;
            }
            if (open(s)) {
                sl.setBlock(p, wil, 2);
                n++;
            }
        }
        return n;
    }

    /** May a door replace this block? Air, water, or a soft thing without collision (grass, a flower, snow layer, a carpet). */
    public static boolean open(BlockState s) {
        if (s.isAir() || s.getFluidState().is(Fluids.WATER) && s.getBlock() == Blocks.WATER) {
            return true;
        }
        return s.canBeReplaced() || s.getFluidState().isEmpty() && !s.blocksMotion() && s.getBlock() != Blocks.BARRIER;
    }

    public static void geluid(ServerLevel sl, Deur d, boolean open) {
        sl.playSound(null, midden(d), open ? SoundEvents.WOODEN_DOOR_OPEN : SoundEvents.WOODEN_DOOR_CLOSE, SoundSource.BLOCKS, 0.8f, 0.8f);
    }
}
