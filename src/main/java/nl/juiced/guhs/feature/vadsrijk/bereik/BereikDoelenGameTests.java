/**
 * W-BEREIK: dumps every spot the reachability check (tools/vadsrijk/bereikcheck.py) must test, straight from the running game
 * code, into {@code tools/vadsrijk/bereik_doelen.json}:
 * <ul>
 *   <li>every public static BlockPos / Map&lt;String, BlockPos&gt; / Collection&lt;BlockPos&gt; of every Vadsrijk {@code *Plekken}
 *       class (NPC spots, quest POIs, area targets, boss spots, collectables, secrets, wereld POIs) + {@code QuestPlek};</li>
 *   <li>all NPC definitions (id, spot, role), all boss arenas (centre, radius, door), all mob spawners, all airship lines
 *       (both pier spots + the docked ship), all puzzles/secrets (anchor point).</li>
 * </ul>
 * Run: {@code gradle_slot.sh <tree> runGameTestServer -Pgt=BereikDoelenGameTests}. The json is committed so the python check
 * runs without gradle; rerun this after quest/NPC/POI changes.
 */
public class BereikDoelenGameTests {
    private static final String PAKKET = "nl.juiced.guhs.feature.vadsrijk.";

    @GuhTest(template = "empty", batch = "vadsrijk_bereik", timeoutTicks = 400)
    public static void dumpDoelen(GameTestHelper helper) {
        JsonObject o = new JsonObject();
        o.addProperty("_", "GENERATED by BereikDoelenGameTests (W-BEREIK) for tools/vadsrijk/bereikcheck.py");
        // 1. the zone NPC/POI registries are filled at class init or by the zone Npcs classes: touch those first
        for (String c : List.of("zone2.npc.Z2Npcs", "zone3.npc.Z3Npcs", "zone4.verhaal.Z4Npcs", "zone5.verhaal.Z5Npcs", "zone6.verhaal.Z6Npcs",
                "ambacht.AmbachtNpcs", "gilden.BondNpcs", "zone6.verhaal.Z6Lijn")) {
            try {
                Class.forName(PAKKET + c, true, BereikDoelenGameTests.class.getClassLoader());
            } catch (Throwable t) {
                // (not fatal: the class may be gone)
            }
        }
        // 2. reflection over all *Plekken classes
        JsonObject velden = new JsonObject();
        TreeSet<String> klassen = new TreeSet<>();
        ModFileScanData scan = ModList.get().getModFileById(Guhs.MODID).getFile().getScanResult();
        for (ModFileScanData.ClassData cd : scan.getClasses()) {
            String n = cd.clazz().getClassName();
            String kort = n.substring(n.lastIndexOf('.') + 1);
            if (n.startsWith(PAKKET) && !n.contains(".client.") && !kort.contains("$") && (kort.endsWith("Plekken") || kort.equals("QuestPlek"))) {
                klassen.add(n);
            }
        }
        List<String> fouten = new ArrayList<>();
        for (String n : klassen) {
            try {
                Class<?> c = Class.forName(n, true, BereikDoelenGameTests.class.getClassLoader());
                String kort = n.substring(PAKKET.length());
                for (Field f : c.getDeclaredFields()) {
                    if (!Modifier.isStatic(f.getModifiers()) || !Modifier.isPublic(f.getModifiers())) {
                        continue;
                    }
                    Object v = f.get(null);
                    JsonObject veld = new JsonObject();
                    voeg(veld, "", v);
                    if (veld.size() > 0) {
                        velden.add(kort + "." + f.getName(), veld);
                    }
                }
            } catch (Throwable t) {
                fouten.add(n + ": " + t);
            }
        }
        o.add("velden", velden);
        // 3. NPCs
        JsonArray npcs = new JsonArray();
        for (NpcDef d : Npcs.alle()) {
            JsonObject n = new JsonObject();
            n.addProperty("id", d.id());
            n.add("pos", pos(d.plek()));
            n.addProperty("rol", d.rol() == null ? "" : d.rol());
            n.addProperty("gedrag", d.gedrag().name());
            npcs.add(n);
        }
        o.add("npcs", npcs);
        // 4. arenas
        JsonArray ar = new JsonArray();
        for (String id : Arenas.ids()) {
            Arena a = Arenas.van(id);
            if (a == null) {
                continue;
            }
            JsonObject j = new JsonObject();
            j.addProperty("id", id);
            j.add("centrum", pos(a.centrum()));
            j.addProperty("straal", a.straal());
            j.add("deur", pos(a.deur()));
            j.addProperty("onder", a.onder());
            j.addProperty("boven", a.boven());
            ar.add(j);
        }
        o.add("arenas", ar);
        // 5. spawners + areas (as on the wiki)
        JsonObject wiki = WikiExport.bouw();
        o.add("spawners", wiki.get("spawners"));
        o.add("gebieden", wiki.get("gebieden"));
        // 6. airship lines
        JsonArray lijnen = new JsonArray();
        List<Lijnen.Lijn> alle = new ArrayList<>(Lijnen.ALLE);
        if (alle.stream().noneMatch(l -> l.id().equals(nl.juiced.guhs.feature.vadsrijk.zone6.verhaal.Z6Lijn.ID))) {
            alle.add(nl.juiced.guhs.feature.vadsrijk.zone6.verhaal.Z6Lijn.LE);
        }
        for (Lijnen.Lijn l : alle) {
            if (l.test()) {
                continue;
            }
            JsonObject j = new JsonObject();
            j.addProperty("id", l.id());
            for (Lijnen.Haven h : List.of(l.a(), l.b())) {
                JsonObject hj = new JsonObject();
                hj.addProperty("id", h.id());
                hj.addProperty("zone", h.zone());
                hj.add("plek", pos(h.plek()));
                Vec3 d = h.dok();
                JsonArray dj = new JsonArray();
                dj.add(Math.round(d.x * 10) / 10.0);
                dj.add(Math.round(d.y * 10) / 10.0);
                dj.add(Math.round(d.z * 10) / 10.0);
                hj.add("dok", dj);
                j.add(h == l.a() ? "a" : "b", hj);
            }
            lijnen.add(j);
        }
        o.add("lijnen", lijnen);
        // 7. puzzles and secrets
        JsonArray pz = new JsonArray();
        try {
            if (Puzzels.defs().isEmpty()) {
                Puzzels.laad(helper.getLevel().getServer());
            }
            for (PuzzelDef d : Puzzels.defs()) {
                JsonObject j = new JsonObject();
                j.addProperty("id", d.id());
                j.addProperty("zone", d.zone());
                j.addProperty("soort", d.soort());
                j.addProperty("stil", d.stil());
                BlockPos p = d.anker().punt();
                if (p != null) {
                    j.add("pos", pos(p));
                }
                j.addProperty("breed", d.breed());
                j.addProperty("diep", d.diep());
                pz.add(j);
            }
        } catch (Throwable t) {
            fouten.add("puzzels: " + t);
        }
        o.add("puzzels", pz);
        // 8. transport links a survival player can use (right-click / walk-in teleports), see NOTITIES_W_BEREIK
        JsonArray links = new JsonArray();
        try {
            link(links, "gondel z2", nl.juiced.guhs.feature.vadsrijk.zone2.wereld.Z2WereldPlekken.GONDEL_DAL,
                    nl.juiced.guhs.feature.vadsrijk.zone2.wereld.Z2WereldPlekken.GONDEL_BERG, true);
        } catch (Throwable t) {
            fouten.add("gondel: " + t);
        }
        try {
            for (var l : nl.juiced.guhs.feature.vadsrijk.zone3.wereld.Z3WereldPlekken.LIFTEN) {
                link(links, "lift z3 " + l.id(), l.onder(), l.boven(), true);
            }
        } catch (Throwable t) {
            fouten.add("z3 liften: " + t);
        }
        try {
            for (var l : nl.juiced.guhs.feature.vadsrijk.zone5.wezens.Z5WezensPlekken.LUIKEN) {
                link(links, "luik z5 " + l.id(), l.klik(), l.naar(), false);
            }
        } catch (Throwable t) {
            fouten.add("z5 luiken: " + t);
        }
        try {
            BlockPos ingang = null;
            for (var l : nl.juiced.guhs.feature.vadsrijk.zone6.wezens.Z6Bouw.luiken()) {
                if (ingang == null) {
                    ingang = l.klik();
                }
                link(links, "luik z6 " + l.id(), l.klik(), l.naar() != null ? l.naar() : ingang, false);
            }
        } catch (Throwable t) {
            fouten.add("z6 luiken: " + t);
        }
        try {
            var r = nl.juiced.guhs.feature.vadsrijk.zone6.raid.Z6RaidPlekken.class;
            BlockPos poort = (BlockPos) r.getMethod("poort").invoke(null), buiten = (BlockPos) r.getMethod("buiten").invoke(null);
            BlockPos midden = (BlockPos) r.getMethod("midden", int.class).invoke(null, 0), uit = (BlockPos) r.getMethod("uitgang").invoke(null);
            link(links, "raid z6 in", poort, midden.offset(8, 0, 0), false);
            link(links, "raid z6 uit", uit, buiten, false);
        } catch (Throwable t) {
            fouten.add("raid: " + t);
        }
        try {   // the story brings you to the Wolkwaldroom door from the middle blowhole (z5_hq08)
            link(links, "verhaal z5 spuitgat->wolkwaldroom", nl.juiced.guhs.feature.vadsrijk.zone5.verhaal.Z5VerhaalPlekken.SPUITGAT,
                    nl.juiced.guhs.feature.vadsrijk.zone5.wezens.Z5WezensPlekken.WOLKWALDROOM_DEUR, false);
        } catch (Throwable t) {
            fouten.add("wolkwaldroom: " + t);
        }
        o.add("links", links);
        JsonArray fj = new JsonArray();
        fouten.forEach(fj::add);
        o.add("fouten", fj);
        // write: tools/vadsrijk/bereik_doelen.json of the project (walk up from the run folder)
        Path p = Path.of("").toAbsolutePath();
        Path doel = null;
        for (Path q = p; q != null; q = q.getParent()) {
            if (Files.isDirectory(q.resolve("tools").resolve("vadsrijk"))) {
                doel = q.resolve("tools").resolve("vadsrijk").resolve("bereik_doelen.json");
                break;
            }
        }
        if (doel == null) {
            doel = p.resolve("bereik_doelen.json");
        }
        try {
            Files.writeString(doel, new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create().toJson(o) + "\n", StandardCharsets.UTF_8);
        } catch (Exception e) {
            helper.fail("cannot write " + doel + ": " + e);
            return;
        }
        com.mojang.logging.LogUtils.getLogger().info("[W-BEREIK] targets -> {} ({} fields, {} npcs, {} arenas, {} lines, {} puzzles, {} errors)", doel, velden.size(),
                npcs.size(), ar.size(), lijnen.size(), pz.size(), fouten.size());
        helper.assertTrue(npcs.size() > 50, "too few NPCs: " + npcs.size());
        helper.succeed();
    }

    private static void link(JsonArray a, String naam, BlockPos van, BlockPos naar, boolean beide) {
        if (van == null || naar == null) {
            return;
        }
        JsonObject j = new JsonObject();
        j.addProperty("naam", naam);
        j.add("van", pos(van));
        j.add("naar", pos(naar));
        j.addProperty("beide", beide);
        a.add(j);
    }

    private static void voeg(JsonObject uit, String sleutel, Object v) {
        if (v instanceof BlockPos b) {
            uit.add(sleutel.isEmpty() ? "_" : sleutel, pos(b));
        } else if (v instanceof Map<?, ?> m) {
            for (Map.Entry<?, ?> e : m.entrySet()) {
                if (e.getValue() instanceof BlockPos || e.getValue() instanceof Collection<?>) {
                    voeg(uit, (sleutel.isEmpty() ? "" : sleutel + ".") + e.getKey(), e.getValue());
                }
            }
        } else if (v instanceof Collection<?> c) {
            int i = 0;
            for (Object x : c) {
                i++;
                if (x instanceof BlockPos b) {
                    uit.add((sleutel.isEmpty() ? "" : sleutel + ".") + i, pos(b));
                }
            }
        }
    }

    private static JsonArray pos(BlockPos b) {
        JsonArray a = new JsonArray();
        a.add(b.getX());
        a.add(b.getY());
        a.add(b.getZ());
        return a;
    }
}
