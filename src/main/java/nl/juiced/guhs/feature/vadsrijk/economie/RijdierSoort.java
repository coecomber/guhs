package nl.juiced.guhs.feature.vadsrijk.economie;

import java.util.Locale;

import javax.annotation.Nullable;

/**
 * All mounts of the Vadsrijk (the mount screen shows them in this order). Speed is the ridden movement speed (0.1 = the normal
 * walking speed of a player, so 0.35 = 350 %); jump is the upward velocity of a hop ({@link #springHoogte} turns it into blocks).
 * Both grow a little with the mount's level (1..{@link #MAX_LEVEL}, xp from riding; the growth per level and a global multiplier
 * are knobs in the balans file, section {@code [rijdieren]}: {@link Balans}). The mounts work in every zone of the dimension.
 * <p>I-MOUNTS (2026-11-04): the Hoedhupper and the Klodderros are gone (the user: they didn't fit the line-up). Saved ownership of
 * them ({@code rijdieren.hoedhupper} / {@code .klodderros}) is simply ignored: every lookup goes through {@link #values()} /
 * {@link #van}, which return nothing for an unknown id.
 * <ul>
 *   <li>{@link #PLUIMGUH}: THE main mount (placeholder slot: the user is still choosing the final look; the model is generated by
 *       tools/features/vadsrijk_rijdieren.py and can be swapped there). Has colour variants ({@link PluimKleur}); the 3 starters
 *       are 3 of them (zone 3 main quest: {@code Rijdieren.kiesStarter}).</li>
 *   <li>{@link #KNUFFELHERT}: a soft deer with little antlers; return quest in zone 1 (Sporenwoud, "Het Knuffelhert").</li>
 *   <li>{@link #GUHWOLF}: a snow wolf with a scarf; return quest in zone 2 (Kandijkom / Splinterkloof, "De verdwaalde Guhwolf").</li>
 *   <li>{@link #WOLKENSCHAAPJE}: a round woolly sheep that hovers a bit: falls slowly and has a double jump (the return quest of
 *       Stalmeester Hoefje, {@code Rijdieren.geefEerste}; also for sale at the stal). Every mount comes after the zone-3 starter
 *       Pluimguh: the stal sells only once you own one.</li>
 *   <li>{@link #SLAKKIE}: the caravan snail as a slow luxury mount with a little seat (stal).</li>
 * </ul>
 */
public enum RijdierSoort {
    // (I-MOUNTS) speed in % of walking: Pluimguh 350, Knuffelhert 320 (jumps high, ~5 blocks), Guhwolf 370 (the fastest, small
    // hop ~2.4 blocks), Wolkenschaapje 300 (+ double jump and slow fall), Slakkie 85 (half of its old 170 %: slow luxury)
    // (T-RIJDIER) + the entity size (width, height) and the traits; three new land mounts (see the class javadoc)
    PLUIMGUH(0.35, 0.72, 0, 2.10, "pluimguh", 1.4f, 2.6f, Eigenschap.KLEUREN),
    KNUFFELHERT(0.32, 0.92, 0, 1.95, "quest", 1.3f, 2.4f),
    GUHWOLF(0.37, 0.60, 0, 1.86, "quest", 1.3f, 2.0f),
    WOLKENSCHAAPJE(0.30, 0.62, 1200, 1.20, "stal", 1.2f, 1.2f, Eigenschap.ZWEEFT),
    SLAKKIE(0.085, 0.45, 2500, 1.45, "stal", 1.1f, 1.5f),
    /** T-RIJDIER: a springy beach hare: the highest jump (~5.8 blocks), a bit slower. Secret: find 10 hidden knuffels. */
    DUINHUPPER(0.29, 0.98, 0, 1.15, "geheim", 1.1f, 1.4f),
    /** T-RIJDIER: a cloud-whale calf that floats a little (slow fall + double jump, like the sheep but faster). 20 Gouden Veren. */
    WOLKWALKALFJE(0.34, 0.64, 0, 1.30, "veren", 1.4f, 1.6f, Eigenschap.ZWEEFT),
    /** T-RIJDIER: a sturdy piglet with a mushroom-cap saddle: shrugs off the first hit. First kill of the Opperzwam. */
    ZWAMZWIJNTJE(0.33, 0.66, 0, 1.10, "baas", 1.2f, 1.4f, Eigenschap.STEVIG),
    /**
     * T-Z4BOOT (T-INT: on t-rijdier's species API): the player's own guh sailboat (zone 4, decision W-2), a mount on WATER; speed
     * 300 % = a top speed of 0.6 blocks a tick at level 1 (zone4.boot.BootFysica), no jump; quest "Boot.geef" early in the zone-4
     * story. Its entity + icon live in zone4.boot.BootSpul (EcoSpul skips water species), its looks in its own screen.
     */
    ZEILBOOTJE(0.30, 0.0, 0, 0.40, "quest", 2.0f, 1.1f, Eigenschap.WATER),
    /**
     * U-TAPIJT: the flying carpet (zone 6 Zijdeland, Tapijtweefster Knoopje: {@code tapijt.Tapijt.geef}). Speed 360 % = a top speed of
     * ~0.76 blocks a tick at level 1 (tapijt.TapijtBalans {@code topfactor}), a small hop; it hovers ~1.25 blocks over ground and
     * water and glides/drifts (its own entity + physics: tapijt.TapijtEntity, tapijt.TapijtFysica). The rider sits cross-legged.
     */
    TAPIJT(0.36, 0.40, 0, 0.30, "quest", 2.0f, 0.5f, Eigenschap.GLIJDT),
    /**
     * U-Z6WEZENS: the Bultguh (camel-guh, zone 6 Zijdeland): speed 330 %, +30 % on sand ({@link Eigenschap#ZANDLOPER}), and TWO seats:
     * a second player can ride along behind ({@link Eigenschap#TANDEM}). Quest (the stal of Rozenkloof, u-z6verhaal:
     * {@code zone6.bultguh.Bultguh.geef}); looks/coats in zone6.bultguh.Bultguh.
     */
    BULTGUH(0.33, 0.60, 0, 1.95, "quest", 1.6f, 2.5f, Eigenschap.TANDEM, Eigenschap.ZANDLOPER);

    /**
     * T-RIJDIER: what a mount can do besides walking and jumping (one place; add a value for a new behaviour, e.g. a water mount).
     * <ul>
     *   <li>{@link #KLEUREN}: has the Pluimguh's own colour enum {@link PluimKleur} (one texture per colour); every other mount
     *       gets its coat colours from {@code rijdier.Uiterlijk} (a "vacht");</li>
     *   <li>{@link #ZWEEFT}: falls slowly and can jump once more in the air;</li>
     *   <li>{@link #STEVIG}: the first hit doesn't scare it (the second within 10 s does).</li>
     * </ul>
     */
    public enum Eigenschap {
        KLEUREN, ZWEEFT, STEVIG,
        /** T-INT (t-z4boot): sails on water instead of walking (own entity, physics, renderer and looks screen). */
        WATER,
        /** U-TAPIJT: hovers over ground and water and glides with momentum (the flying carpet: tapijt.TapijtEntity). */
        GLIJDT,
        /** U-Z6WEZENS: two seats, a second player can ride along behind the owner (the Bultguh). */
        TANDEM,
        /** U-Z6WEZENS: +30 % speed on sand (the Bultguh). */
        ZANDLOPER
    }

    public static final int MAX_LEVEL = 10;
    /** Every mount steps up this many blocks while walking (no jump needed): a 2-block ledge, stairs, slabs. */
    public static final double STAP = 2.0;
    /** Speed growth per level above 1 (default; balans {@code [rijdieren] groei_snelheid}): +1.5 % a level, +13.5 % at the max. */
    public static final double GROEI_SNELHEID = 0.015;
    /** Jump growth per level above 1 (default; balans {@code [rijdieren] groei_sprong}): +0.01 a level, ~+0.6 blocks at the max. */
    public static final double GROEI_SPRONG = 0.01;

    public final double snelheid, sprong;
    /** Price at the stal in brons (0 = not for sale: quest or boss loot). */
    public final long prijs;
    /** Where the rider sits (blocks above the mount's feet). */
    public final double zit;
    /** Where you get it: "quest", "baas", "stal", "geheim", "veren" or "pluimguh" (per colour, see {@link PluimKleur}). */
    public final String bron;
    /** T-RIJDIER: the entity size (blocks), used by EcoSpul's entity registration. */
    public final float breedte, hoogte;
    private final java.util.Set<Eigenschap> eigenschappen;

    /** (the old 5-number form: size 1.3 x 2.0, no traits) */
    RijdierSoort(double snelheid, double sprong, long prijs, double zit, String bron) {
        this(snelheid, sprong, prijs, zit, bron, 1.3f, 2.0f);
    }

    RijdierSoort(double snelheid, double sprong, long prijs, double zit, String bron, float breedte, float hoogte, Eigenschap... eigenschappen) {
        this.snelheid = snelheid;
        this.sprong = sprong;
        this.prijs = prijs;
        this.zit = zit;
        this.bron = bron;
        this.breedte = breedte;
        this.hoogte = hoogte;
        this.eigenschappen = eigenschappen.length == 0 ? java.util.EnumSet.noneOf(Eigenschap.class) : java.util.EnumSet.copyOf(java.util.Arrays.asList(eigenschappen));
    }

    public boolean heeft(Eigenschap e) {
        return eigenschappen.contains(e);
    }

    public String id() {
        return name().toLowerCase(Locale.ROOT);
    }

    public String naamKey() {
        return "vadsrijk.economie.rijdier." + id();
    }

    /** Has the Pluimguh colour enum ({@link PluimKleur}); the other mounts get coat colours from {@code rijdier.Uiterlijk}. */
    public boolean kleuren() {
        return heeft(Eigenschap.KLEUREN);
    }

    /** (T-Z4BOOT) Sails on water instead of walking (the Zeilbootje: zone4.boot.BootEntity, its own physics and screen). */
    public boolean water() {
        return heeft(Eigenschap.WATER);
    }

    /** Hovers: falls slowly and can jump once more in the air. */
    public boolean zweeft() {
        return heeft(Eigenschap.ZWEEFT);
    }

    /** U-TAPIJT: hovers and glides (the flying carpet). */
    public boolean glijdt() {
        return heeft(Eigenschap.GLIJDT);
    }

    /** U-Z6WEZENS: how many players may ride it (the owner + a passenger behind with TANDEM). */
    public int zitplaatsen() {
        return heeft(Eigenschap.TANDEM) ? 2 : 1;
    }

    /** T-RIJDIER: shrugs off the first hit (see {@code Rijdieren.geraakt}). */
    public boolean stevig() {
        return heeft(Eigenschap.STEVIG);
    }

    /** Movement speed at this level (balans: x {@code snelheid}, + {@code groei_snelheid} per level). */
    public double snelheid(int level) {
        return snelheid * Balans.snelheid() * (1 + Balans.groeiSnelheid() * (lvl(level) - 1));
    }

    /** Jump strength at this level (balans: + {@code groei_sprong} per level, x {@code sprong}). */
    public double sprong(int level) {
        return (sprong + Balans.groeiSprong() * (lvl(level) - 1)) * Balans.sprong();
    }

    private static int lvl(int level) {
        return Math.max(1, Math.min(MAX_LEVEL, level));
    }

    /** How high (blocks) a hop with this upward velocity goes (vanilla gravity 0.08 and drag 0.98 per tick). */
    public static double springHoogte(double v) {
        double y = 0;
        for (int i = 0; i < 200 && v > 0; i++) {
            y += v;
            v = (v - 0.08) * 0.98;
        }
        return y;
    }

    /**
     * The mount knobs (I-MOUNTS), pushed from the one balans file {@code config/guhs-vadsrijk-balans.toml}, section
     * {@code [rijdieren]} (klassen's {@code KlasseBalans} reads/writes it; {@code /guhs vadsrijk balans rijdieren <sleutel> <x>}):
     * {@code snelheid} and {@code sprong} are multipliers on every mount (1.0), {@code groei_snelheid} / {@code groei_sprong} the
     * growth per level. Server side; the ridden mount gets its effective numbers synced ({@link RijdierEntity}).
     */
    public static final class Balans {
        private static volatile double snelheid = 1, sprong = 1, groeiSnelheid = GROEI_SNELHEID, groeiSprong = GROEI_SPRONG;

        private Balans() {
        }

        public static double snelheid() {
            return snelheid;
        }

        public static double sprong() {
            return sprong;
        }

        public static double groeiSnelheid() {
            return groeiSnelheid;
        }

        public static double groeiSprong() {
            return groeiSprong;
        }

        /** From KlasseBalans (file/command); clamped so nothing silly happens. */
        public static void zet(double snel, double spr, double groeiSnel, double groeiSpr) {
            snelheid = Math.max(0.1, Math.min(3, snel));
            sprong = Math.max(0.3, Math.min(2, spr));
            groeiSnelheid = Math.max(0, Math.min(0.1, groeiSnel));
            groeiSprong = Math.max(0, Math.min(0.05, groeiSpr));
        }
    }

    /** Xp (blocks ridden) from this level to the next. */
    public static long xpNodig(int level) {
        return level >= MAX_LEVEL ? 0 : 150L * level;
    }

    @Nullable
    public static RijdierSoort van(String id) {
        for (RijdierSoort s : values()) {
            if (s.id().equals(id)) {
                return s;
            }
        }
        return null;
    }

    /**
     * The colour variants of the Pluimguh. The first three are the starters (pick one free in the zone-3 quest, buy the other two at
     * the stal). {@link #GOUD} is hidden in the screen until you have it (a boss reward later).
     */
    public enum PluimKleur {
        ROZE(0xFFFF9CC8, true, 800, "starter"),
        MINT(0xFF9CEBC8, true, 800, "starter"),
        LAVENDEL(0xFFC4A8F4, true, 800, "starter"),
        HONING(0xFFFFCC66, false, 2000, "stal"),
        WOLKWIT(0xFFF6F4FF, false, 0, "quest"),
        STERRENNACHT(0xFF3A3478, false, 0, "baas"),
        GOUD(0xFFFFD040, false, 0, "goud"),
        /** T-RIJDIER: ice-blue with a glitter shine; first kill of Spiegelzucht (zone 2, De Spiegelburcht). */
        KRISTAL(0xFFB8E8FF, false, 0, "baas"),
        /** T-RIJDIER: warm lantern orange (zone 4 Lampionkust later: {@code Rijdieren.geefKleur}); for now 12 Gouden Veren. */
        LAMPION(0xFFFFA860, false, 0, "veren"),
        // U-GROTKERKER: the six cave colours, rare from a cave dungeon's end chest (10 % per clear, sure after 15: vint.RijdierBuit);
        // hidden in the colour row until you own them (verborgen)
        GLIMZWAM(0xFF96E8B0, false, 0, "grot"),
        AMETHIST(0xFFBC96F2, false, 0, "grot"),
        WORTELHOUT(0xFFC69060, false, 0, "grot"),
        KORAAL(0xFFFF847A, false, 0, "grot"),
        ONWEER(0xFF848EB2, false, 0, "grot"),
        ZOUTROZE(0xFFFFD6DE, false, 0, "grot");

        /** The swatch colour in the screen (ARGB). */
        public final int kleur;
        public final boolean starter;
        /** Price at the stal in brons (0 = not for sale). */
        public final long prijs;
        public final String bron;

        PluimKleur(int kleur, boolean starter, long prijs, String bron) {
            this.kleur = kleur;
            this.starter = starter;
            this.prijs = prijs;
            this.bron = bron;
        }

        public String id() {
            return name().toLowerCase(Locale.ROOT);
        }

        public String naamKey() {
            return "vadsrijk.economie.pluimkleur." + id();
        }

        public boolean verborgen() {
            return this == GOUD || "grot".equals(bron);   // (U-GROTKERKER: the cave colours too)
        }

        public static PluimKleur van(String id) {
            for (PluimKleur k : values()) {
                if (k.id().equals(id)) {
                    return k;
                }
            }
            return ROZE;
        }

        @Nullable
        public static PluimKleur vanOfNull(String id) {
            for (PluimKleur k : values()) {
                if (k.id().equals(id)) {
                    return k;
                }
            }
            return null;
        }
    }
}
