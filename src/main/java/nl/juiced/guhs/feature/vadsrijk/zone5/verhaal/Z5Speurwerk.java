/**
 * The detective work of "Verraad in de stad" (zone 5): the clues in the player's Speurdersboekje, the interrogations with dialogue
 * choices, and the evidence board where you accuse the traitor. Data: data/guhs/vadsrijk/z5verhaal/speurwerk.json (generated by
 * tools/features/vadsrijk_t_z5verhaal.py: clue ids, the suspects and which clue clears them, every interrogation's speakers and
 * which question yields its clue); texts {@code vadsrijk.z5verhaal.bewijs.* / verhoor.* / bord.*}.
 * <ul>
 *   <li><b>Clues</b>: per player in {@code extra("npc").z5_bewijs} (id -> true). Found at a spot (the lectern, the cadets'
 *       lockers, the night logbook: Z5Haken) or by asking the right question in an interrogation.</li>
 *   <li><b>Interrogation</b> ({@link #verhoor}): the intro pages, then a choice of questions; every question has its own answer; ONE
 *       of them yields the clue and counts {@code meld("z5_verhoor", id)}; you may ask everything, then "Dat was het".</li>
 *   <li><b>Evidence board</b> ({@link #bord}): at Inspecteur Snuffelaar (role z5_bewijsbord) or with the Speurdersboekje (right
 *       click). It lists found clues (✔) and the suspects (cleared ones marked). During z5_hq07 it offers "Beschuldig X": the right
 *       one counts {@code meld("z5_beschuldigd", "juist")} and starts the unmasking; a wrong one explains which clue clears them.</li>
 * </ul>
 */
public final class Z5Speurwerk {
    private static final Logger LOG = LogUtils.getLogger();
    public static final String BESTAND = "/data/guhs/vadsrijk/z5verhaal/speurwerk.json";
    public static final String MAP = "z5_bewijs";
    static final String SLEUTEL_VERHOOR = "vr_z5_verhoor", SLEUTEL_BORD = "vr_z5_bord";
    static final int KLAAR = 99, VERDER = 98, BESCHULDIG = 40;
    static final String Z = Z5Verhaal.Z;

    public record Verhoor(String id, String npc, String bewijs, int sleutel, List<String> intro, List<List<String>> vragen) {
    }

    public record Verdachte(String id, String npc, String vrij) {
        public boolean verrader() {
            return vrij.isEmpty();
        }
    }

    private static volatile boolean geladen;
    static final List<String> BEWIJS = new ArrayList<>();
    static final List<String> ZEKER = new ArrayList<>();
    static final Map<String, Verdachte> VERDACHTEN = new LinkedHashMap<>();
    static final Map<String, Verhoor> VERHOREN = new LinkedHashMap<>();

    /** The open interrogation of a player: which one, the questions asked so far. */
    private record Open(String id, int entity, Set<Integer> gevraagd) {
    }

    private static final Map<UUID, Open> OPEN = new ConcurrentHashMap<>();
    /** After the right accusation: the unmasking runs when the board closes. */
    private static final Set<UUID> ONTMASKER_NA = ConcurrentHashMap.newKeySet();

    private Z5Speurwerk() {
    }

    static synchronized void laad() {
        if (geladen) {
            return;
        }
        geladen = true;
        try (InputStream in = Z5Speurwerk.class.getResourceAsStream(BESTAND)) {
            if (in == null) {
                LOG.error("Vadsrijk z5verhaal: {} is missing", BESTAND);
                return;
            }
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            root.getAsJsonArray("bewijs").forEach(e -> BEWIJS.add(e.getAsString()));
            root.getAsJsonArray("zeker").forEach(e -> ZEKER.add(e.getAsString()));
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("verdachten").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                VERDACHTEN.put(e.getKey(), new Verdachte(e.getKey(), o.get("npc").getAsString(), o.get("vrij").getAsString()));
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("verhoren").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                List<String> intro = new ArrayList<>();
                o.getAsJsonArray("intro").forEach(x -> intro.add(x.getAsString()));
                List<List<String>> vragen = new ArrayList<>();
                for (JsonElement v : o.getAsJsonArray("vragen")) {
                    List<String> l = new ArrayList<>();
                    v.getAsJsonArray().forEach(x -> l.add(x.getAsString()));
                    vragen.add(List.copyOf(l));
                }
                VERHOREN.put(e.getKey(), new Verhoor(e.getKey(), o.get("npc").getAsString(), o.get("bewijs").getAsString(), o.get("sleutel").getAsInt(),
                        List.copyOf(intro), List.copyOf(vragen)));
            }
        } catch (Exception e) {
            LOG.error("Vadsrijk z5verhaal: could not read {}", BESTAND, e);
        }
    }

    static void init() {
        laad();
        Praat.luister(SLEUTEL_VERHOOR, Z5Speurwerk::verhoorAntwoord);
        Praat.luister(SLEUTEL_BORD, Z5Speurwerk::bordAntwoord);
    }

    // ---- clues ----------------------------------------------------------------------------------------------------------------

    public static boolean heeft(ServerPlayer p, String bewijs) {
        return Questlog.map(p, MAP).getBooleanOr(bewijs, false);
    }

    public static int aantal(ServerPlayer p) {
        int n = 0;
        for (String b : BEWIJS) {
            n += heeft(p, b) ? 1 : 0;
        }
        return n;
    }

    /** A new clue in the Speurdersboekje (once): a chat line with its name and the count. */
    public static void vind(ServerPlayer p, String bewijs) {
        CompoundTag m = Questlog.map(p, MAP);
        if (m.getBooleanOr(bewijs, false) || !BEWIJS.contains(bewijs)) {
            return;
        }
        m.putBoolean(bewijs, true);
        p.level().playSound(null, p.blockPosition(), SoundEvents.BOOK_PAGE_TURN, SoundSource.PLAYERS, 1f, 1.1f);
        p.sendSystemMessage(Component.translatable(Z + "bewijs.gevonden", Component.translatable(Z + "bewijs." + bewijs + ".titel"), aantal(p), BEWIJS.size())
                .withStyle(ChatFormatting.AQUA));
        Tips.toon(p, "vadsrijk.npc.tip.z5_bord");
    }

    // ---- interrogations --------------------------------------------------------------------------------------------------------

    /** The interrogation of this NPC that a quest of this player waits for now (null: none). */
    @Nullable
    static Verhoor open(ServerPlayer p, String npc) {
        for (Verhoor v : VERHOREN.values()) {
            if (v.npc().equals(npc) && Z5Haken.wachtOp(p, "z5_verhoor:" + v.id())) {
                return v;
            }
        }
        return null;
    }

    /** Starts the interrogation: the intro, then the questions. */
    public static void verhoor(ServerPlayer p, @Nullable Entity npc, Verhoor v) {
        Open o = new Open(v.id(), npc == null ? -1 : npc.getId(), new HashSet<>());
        OPEN.put(p.getUUID(), o);
        List<Praat.Regel> r = regels(p, npc, v.intro(), Z + "verhoor." + v.id() + ".intro.");
        Praat.scene(p, SLEUTEL_VERHOOR, r, vragen(v, o));
        Tips.toon(p, "vadsrijk.npc.tip.z5_verhoor");
    }

    private static Praat.Optie[] vragen(Verhoor v, Open o) {
        List<Praat.Optie> l = new ArrayList<>();
        for (int k = 0; k < v.vragen().size(); k++) {
            if (!o.gevraagd().contains(k)) {
                l.add(new Praat.Optie(k, Z + "verhoor." + v.id() + ".vraag." + k));
            }
        }
        if (o.gevraagd().contains(v.sleutel()) || l.isEmpty()) {
            l.add(new Praat.Optie(KLAAR, Z + "verhoor.klaar"));
        }
        return l.toArray(new Praat.Optie[0]);
    }

    private static void verhoorAntwoord(ServerPlayer p, @Nullable Entity spreker, int optie) {
        Open o = OPEN.get(p.getUUID());
        if (o == null) {
            return;
        }
        Verhoor v = VERHOREN.get(o.id());
        if (optie < 0 || optie == KLAAR || v == null) {
            OPEN.remove(p.getUUID());
            if (optie == KLAAR) {
                Praat.sluit(p);
            }
            return;
        }
        if (optie >= v.vragen().size()) {
            return;
        }
        vraag(p, spreker != null ? spreker : p.level().getEntity(o.entity()), v, o, optie);
    }

    /** Ask question k (also the test path). */
    static void vraag(ServerPlayer p, @Nullable Entity npc, Verhoor v, Open o, int k) {
        o.gevraagd().add(k);
        if (k == v.sleutel()) {
            if (v.bewijs().equals("kaastest")) {   // (the cheese is eaten)
                p.getInventory().clearOrCountMatchingItems(s -> s.is(Z5VerhaalRegistry.item("kaasje")), 1, p.inventoryMenu.getCraftSlots());
            }
            vind(p, v.bewijs());
            NpcApi.meld(p, "z5_verhoor", v.id());
        }
        List<Praat.Regel> r = regels(p, npc, v.vragen().get(k), Z + "verhoor." + v.id() + ".antwoord." + k + ".");
        Praat.scene(p, SLEUTEL_VERHOOR, r, vragen(v, o));
    }

    /** (tests) Ask question k of the interrogation that is open for this player now. */
    static boolean vraagVoorTest(ServerPlayer p, int k) {
        Open o = OPEN.get(p.getUUID());
        Verhoor v = o == null ? null : VERHOREN.get(o.id());
        if (v == null) {
            return false;
        }
        vraag(p, null, v, o, k);
        return true;
    }

    static List<Praat.Regel> regels(ServerPlayer p, @Nullable Entity npc, List<String> sprekers, String prefix) {
        List<Praat.Regel> l = new ArrayList<>();
        for (int i = 0; i < sprekers.size(); i++) {
            l.add(sprekers.get(i).equals("jij") ? new Praat.Regel(p, "vadsrijk.npc.jij", prefix + i) : new Praat.Regel(npc, "", prefix + i));
        }
        return l;
    }

    // ---- the evidence board -------------------------------------------------------------------------------------------------------

    /** May the player accuse someone now (z5_hq07, before the accusation)? */
    static boolean magBeschuldigen(ServerPlayer p) {
        return Z5Haken.wachtOp(p, "z5_beschuldigd:juist");
    }

    /** Opens the board: the clues, the suspects, and (during hq07) the accusation choices. */
    public static void bord(ServerPlayer p, @Nullable Entity spreker) {
        laad();
        MutableComponent sporen = Component.empty();
        for (String b : BEWIJS) {
            boolean ja = heeft(p, b);
            sporen.append(Component.literal(ja ? "\n✔ " : "\n• ").withStyle(ja ? ChatFormatting.DARK_GREEN : ChatFormatting.GRAY))
                    .append(ja ? Component.translatable(Z + "bewijs." + b + ".titel") : Component.translatable(Z + "bord.onbekend"));
        }
        MutableComponent wie = Component.empty();
        for (Verdachte v : VERDACHTEN.values()) {
            wie.append(Component.literal("\n• ")).append(Component.translatable(Z + "verdachte." + v.id()));
            if (!v.verrader() && heeft(p, v.vrij())) {
                wie.append(Component.literal(" (")).append(Component.translatable(Z + "bord.vrij")).append(Component.literal(")"));
            }
        }
        String naam = spreker == null ? Z + "bord.naam" : "";
        List<Praat.Regel> r = new ArrayList<>();
        r.add(new Praat.Regel(spreker, naam, Z + "bord.sporen", aantal(p), BEWIJS.size(), sporen));
        r.add(new Praat.Regel(spreker, naam, Z + "bord.verdachten", wie));
        boolean zeker = ZEKER.stream().allMatch(b -> heeft(p, b));
        if (zeker) {
            r.add(new Praat.Regel(spreker, naam, Z + "bord.zeker"));
        }
        List<Praat.Optie> o = new ArrayList<>();
        if (magBeschuldigen(p)) {
            if (zeker) {
                int i = 0;
                for (Verdachte v : VERDACHTEN.values()) {
                    o.add(new Praat.Optie(BESCHULDIG + i++, Z + "bord.optie.beschuldig." + v.id()));
                }
            } else {
                r.add(new Praat.Regel(spreker, naam, Z + "bord.nog_niet"));
            }
        }
        o.add(new Praat.Optie(VERDER, Z + "bord.optie.verder"));
        Praat.scene(p, SLEUTEL_BORD, r, o.toArray(new Praat.Optie[0]));
    }

    private static void bordAntwoord(ServerPlayer p, @Nullable Entity spreker, int optie) {
        if (optie < 0) {
            if (ONTMASKER_NA.remove(p.getUUID())) {
                Z5Verhaal.ontmasker(p);
            }
            return;
        }
        if (optie == VERDER) {
            Praat.sluit(p);
            return;
        }
        int i = optie - BESCHULDIG;
        List<Verdachte> l = new ArrayList<>(VERDACHTEN.values());
        if (i >= 0 && i < l.size() && magBeschuldigen(p)) {
            beschuldig(p, spreker, l.get(i).id());
        }
    }

    /** Accuse a suspect (also the test path): true = the right one. */
    static boolean beschuldig(ServerPlayer p, @Nullable Entity spreker, String id) {
        Verdachte v = VERDACHTEN.get(id);
        if (v == null) {
            return false;
        }
        String naam = spreker == null ? "vadsrijk.npc.naam.z5_inspecteur" : "";
        if (!v.verrader()) {
            Praat.scene(p, SLEUTEL_BORD, List.of(new Praat.Regel(spreker, naam, Z + "bord.fout", Component.translatable(Z + "bewijs." + v.vrij()))),
                    new Praat.Optie(VERDER, Z + "bord.optie.verder"));
            return false;
        }
        NpcApi.meld(p, "z5_beschuldigd", "juist");
        ONTMASKER_NA.add(p.getUUID());
        Praat.scene(p, SLEUTEL_BORD, List.of(new Praat.Regel(spreker, naam, Z + "bord.juist.0"), new Praat.Regel(spreker, naam, Z + "bord.juist.1")));
        return true;
    }

    /** The Speurdersboekje item: right click opens the board. */
    public static final class Boekje extends net.minecraft.world.item.Item {
        public Boekje(Properties p) {
            super(p);
        }

        @Override
        public net.minecraft.world.InteractionResult use(net.minecraft.world.level.Level level, net.minecraft.world.entity.player.Player player,
                net.minecraft.world.InteractionHand hand) {
            if (player instanceof ServerPlayer sp) {
                bord(sp, null);
            }
            return net.minecraft.world.InteractionResult.SUCCESS;
        }
    }

    /** (dev/tests) forget everything of this player. */
    static void vergeet(ServerPlayer p) {
        OPEN.remove(p.getUUID());
        ONTMASKER_NA.remove(p.getUUID());
        Questlog.data(p).remove(MAP);
    }

    /** (dev) one clue without a message. */
    static void vindStil(ServerPlayer p, String bewijs) {
        Questlog.map(p, MAP).putBoolean(bewijs, true);
    }

    /** (dev) every clue at once. */
    static void allesGevonden(ServerPlayer p) {
        for (String b : BEWIJS) {
            Questlog.map(p, MAP).putBoolean(b, true);
        }
    }
}
