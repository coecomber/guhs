package nl.juiced.guhs.feature.vadsrijk.momenten;

import com.geckolib.animatable.GeoEntity;
import com.geckolib.animatable.instance.AnimatableInstanceCache;
import com.geckolib.animatable.manager.AnimatableManager;
import com.geckolib.animation.AnimationController;
import com.geckolib.animation.RawAnimation;
import com.geckolib.util.GeckoLibUtil;

import net.minecraft.core.particles.ParticleTypes;
import net.minecraft.network.syncher.EntityDataAccessor;
import net.minecraft.network.syncher.EntityDataSerializers;
import net.minecraft.network.syncher.SynchedEntityData;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityDimensions;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.storage.ValueInput;
import net.minecraft.world.level.storage.ValueOutput;
import net.minecraft.world.phys.AABB;
import net.minecraft.world.phys.Vec3;

/**
 * The caravan cart (vr_mom_karavaan): a big friendly snail with a guh face pulling a little cart full of goods; the trader guh
 * ({@link HandelGuh}) rides on the bench. No AI, never hurt, never saved: {@link Karavaan} moves it along the road every tick and
 * removes it when no player is near. Right-click opens the caravan shop. GeckoLib model generated by
 * tools/features/vadsrijk_momenten.py.
 */
public class KaravaanSlak extends Entity implements GeoEntity {
    private static final EntityDataAccessor<Boolean> RIJDT = SynchedEntityData.defineId(KaravaanSlak.class, EntityDataSerializers.BOOLEAN);
    private static final EntityDataAccessor<Boolean> BANG = SynchedEntityData.defineId(KaravaanSlak.class, EntityDataSerializers.BOOLEAN);
    private static final RawAnimation KRUIP = RawAnimation.begin().thenLoop("kruip"), STIL = RawAnimation.begin().thenLoop("stil"),
            SCHRIK = RawAnimation.begin().thenLoop("bang");
    private final AnimatableInstanceCache cache = GeckoLibUtil.createInstanceCache(this);

    public KaravaanSlak(EntityType<?> type, Level level) {
        super(type, level);
        setNoGravity(true);
    }

    @Override
    protected void defineSynchedData(SynchedEntityData.Builder b) {
        b.define(RIJDT, false);
        b.define(BANG, false);
    }

    public void zet(boolean rijdt, boolean bang) {
        if (entityData.get(RIJDT) != rijdt) {
            entityData.set(RIJDT, rijdt);
        }
        if (entityData.get(BANG) != bang) {
            entityData.set(BANG, bang);
        }
    }

    public boolean rijdt() {
        return entityData.get(RIJDT);
    }

    public boolean bang() {
        return entityData.get(BANG);
    }

    @Override
    public void tick() {
        super.tick();
        if (level().isClientSide()) {
            if (rijdt() && random.nextInt(6) == 0) {   // a little slime trail behind the snail
                Vec3 achter = Vec3.directionFromRotation(0, getYRot()).scale(-0.6);
                level().addParticle(ParticleTypes.ITEM_SLIME, getX() + achter.x + (random.nextDouble() - 0.5) * 0.6, getY() + 0.05,
                        getZ() + achter.z + (random.nextDouble() - 0.5) * 0.6, 0, 0, 0);
            }
            if (bang() && random.nextInt(4) == 0) {
                level().addParticle(ParticleTypes.SPLASH, getX(), getY() + 1.6, getZ(), 0, 0.1, 0);
            }
        }
    }

    @Override
    public InteractionResult interact(Player player, InteractionHand hand, Vec3 location) {
        if (hand == InteractionHand.MAIN_HAND && player instanceof ServerPlayer sp) {
            Karavaan.klik(sp);
        }
        return InteractionResult.SUCCESS;
    }

    @Override
    public boolean hurtServer(ServerLevel level, DamageSource source, float amount) {
        return false;
    }

    @Override
    public boolean isPickable() {
        return true;
    }

    @Override
    public boolean isPushable() {
        return false;
    }

    @Override
    public boolean canBeCollidedWith(Entity other) {
        return false;
    }

    @Override
    public boolean isAttackable() {
        return false;
    }

    @Override
    public boolean shouldBeSaved() {
        return false;
    }

    @Override
    protected boolean canAddPassenger(Entity passenger) {
        return getPassengers().isEmpty() && passenger instanceof HandelGuh;
    }

    /** The trader sits on the bench at the front of the cart, right behind the snail's shell. */
    @Override
    protected Vec3 getPassengerAttachmentPoint(Entity passenger, EntityDimensions dimensions, float scale) {
        return new Vec3(0, 0.95, -0.35).yRot(-getYRot() * ((float) Math.PI / 180f));
    }

    public AABB getBoundingBoxForCulling() {
        return getBoundingBox().inflate(1.5, 1, 1.5);
    }

    @Override
    protected void readAdditionalSaveData(ValueInput in) {
    }

    @Override
    protected void addAdditionalSaveData(ValueOutput out) {
    }

    @Override
    public void registerControllers(AnimatableManager.ControllerRegistrar controllers) {
        controllers.add(new AnimationController<KaravaanSlak>("loop", 6, s -> s.setAndContinue(
                s.animatable().bang() ? SCHRIK : s.animatable().rijdt() ? KRUIP : STIL)));
    }

    @Override
    public AnimatableInstanceCache getAnimatableInstanceCache() {
        return cache;
    }
}
