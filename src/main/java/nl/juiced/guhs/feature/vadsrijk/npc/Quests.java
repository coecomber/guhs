package nl.juiced.guhs.feature.vadsrijk.npc;

import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import javax.annotation.Nullable;

import org.slf4j.Logger;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.mojang.logging.LogUtils;

/**
 * The quests of zone 1, read once from the mod's own data/guhs/vadsrijk/npc/quests.json (classpath: the file is generated by
 * tools/features/vadsrijk_npc.py; the order in the file is the order in the questlog).
 */
public final class Quests {
    private static final Logger LOG = LogUtils.getLogger();
    public static final String BESTAND = "/data/guhs/vadsrijk/npc/quests.json";
    /** Zone 2 (tools/features/vadsrijk_z2_npc.py): read after zone 1, same system, its quests come after zone 1's in the questlog. */
    public static final String BESTAND_Z2 = "/data/guhs/vadsrijk/npc/quests_z2.json";
    /** Zone 3 (tools/features/vadsrijk_z3_npc.py): read after zone 2, same system. */
    public static final String BESTAND_Z3 = "/data/guhs/vadsrijk/npc/quests_z3.json";
    /** Zone 4 (tools/features/vadsrijk_t_z4verhaal.py): read after zone 3, same system. */
    public static final String BESTAND_Z4 = "/data/guhs/vadsrijk/npc/quests_z4.json";   // T-Z4VERHAAL
    /** T-Z5VERHAAL: zone 5 Hoogvads (tools/features/vadsrijk_t_z5verhaal.py): read after EVERY earlier zone (its own loop below). */
    public static final String BESTAND_Z5 = "/data/guhs/vadsrijk/npc/quests_z5.json";
    private static volatile Map<String, Quest> alle;

    private Quests() {
    }

    public static Map<String, Quest> alle() {
        Map<String, Quest> a = alle;
        if (a == null) {
            synchronized (Quests.class) {
                if (alle == null) {
                    alle = laad();
                }
                a = alle;
            }
        }
        return a;
    }

    @Nullable
    public static Quest van(String id) {
        return alle().get(id);
    }

    private static Map<String, Quest> laad() {
        Map<String, Quest> m = new LinkedHashMap<>();
        for (String bestand : new String[] {BESTAND, BESTAND_Z2, BESTAND_Z3, BESTAND_Z4}) {
            try (InputStream in = Quests.class.getResourceAsStream(bestand)) {
                if (in == null) {
                    LOG.error("Vadsrijk npc: {} is missing", bestand);
                    continue;
                }
                JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
                for (JsonElement e : root.getAsJsonArray("quests")) {
                    Quest q = quest(e.getAsJsonObject());
                    m.put(q.id(), q);
                }
            } catch (Exception e) {
                LOG.error("Vadsrijk npc: could not read {}", bestand, e);
            }
        }
        leesNa(m, BESTAND_Z5);   // T-Z5VERHAAL
        return Collections.unmodifiableMap(m);
    }

    /** T-Z5VERHAAL: one later zone's quest file, after all the others (so its quests come last in the questlog). */
    private static void leesNa(Map<String, Quest> m, String bestand) {
        try (InputStream in = Quests.class.getResourceAsStream(bestand)) {
            if (in == null) {
                LOG.error("Vadsrijk npc: {} is missing", bestand);
                return;
            }
            JsonObject root = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            for (JsonElement e : root.getAsJsonArray("quests")) {
                Quest q = quest(e.getAsJsonObject());
                m.put(q.id(), q);
            }
        } catch (Exception e) {
            LOG.error("Vadsrijk npc: could not read {}", bestand, e);
        }
    }

    private static Quest quest(JsonObject o) {
        String id = o.get("id").getAsString();
        String gever = str(o, "gever", "");
        List<Quest.Doel> doelen = new ArrayList<>();
        for (JsonElement e : arr(o, "doelen")) {
            JsonObject d = e.getAsJsonObject();
            doelen.add(new Quest.Doel(Quest.Doel.Type.van(d.get("soort").getAsString()), str(d, "doel", "*"), d.has("n") ? d.get("n").getAsInt() : 1,
                    str(d, "bron", ""), d.has("kans") ? d.get("kans").getAsDouble() : 0, str(d, "plek", "")));
        }
        JsonObject b = o.has("beloning") ? o.getAsJsonObject("beloning") : new JsonObject();
        Quest.Beloning bel = new Quest.Beloning(b.has("xp") ? b.get("xp").getAsLong() : 0, b.has("munten") ? b.get("munten").getAsLong() : 0,
                dingen(arr(b, "items")), b.has("wapen") && b.get("wapen").getAsBoolean(), str(b, "loot", ""));
        Map<String, List<String>> praat = new LinkedHashMap<>();
        if (o.has("praat")) {
            for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("praat").entrySet()) {
                praat.put(e.getKey(), strs(e.getValue().getAsJsonArray()));
            }
        }
        List<String> na = strs(arr(o, "na"));
        return new Quest(id, Quest.Soort.van(str(o, "soort", "zij")), gever, str(o, "inleveren", gever), o.has("lv") ? o.get("lv").getAsInt() : 1, na,
                o.has("klasse") ? o.get("klasse").getAsString() : null, o.has("auto") && o.get("auto").getAsBoolean(), List.copyOf(doelen), bel,
                strs(arr(o, "aanbod")), strs(arr(o, "klaar")), praat, str(o, "actie_aanname", ""), str(o, "actie_klaar", ""),
                dingen(arr(o, "start_items")));
    }

    private static List<Quest.Beloning.Ding> dingen(JsonArray a) {
        List<Quest.Beloning.Ding> l = new ArrayList<>();
        for (JsonElement e : a) {
            JsonArray x = e.getAsJsonArray();
            l.add(new Quest.Beloning.Ding(x.get(0).getAsString(), x.size() > 1 ? x.get(1).getAsInt() : 1));
        }
        return List.copyOf(l);
    }

    private static JsonArray arr(JsonObject o, String k) {
        return o.has(k) ? o.getAsJsonArray(k) : new JsonArray();
    }

    private static List<String> strs(JsonArray a) {
        List<String> l = new ArrayList<>();
        for (JsonElement e : a) {
            l.add(e.getAsString());
        }
        return List.copyOf(l);
    }

    private static String str(JsonObject o, String k, String standaard) {
        return o.has(k) && !o.get(k).isJsonNull() ? o.get(k).getAsString() : standaard;
    }
}
