/**
 * 1.10.4: the STAMP kind of {@link WereldPatch}: a whole region of the map tiles (the Ambachtseiland, the Knuffelkamp path) put
 * into the already generated world, block by block. The data ({@code data/guhs/vadsrijk/patch/<naam>.json} with
 * {@code "soort": "stempel"} + its {@code <naam>.stempel.nbt}) is generated by {@code tools/vadsrijk/kamp/ambacht_kaart.py}: per
 * cell the position, the state the LIVE tiles generated there ({@code oud}) and the new state ({@code nieuw}), plus block-entity
 * nbt (signs). Rules per cell ({@link #oordeel}):
 * <ul>
 *   <li>a block entity is never touched (a chest, a sign, a player's furnace);</li>
 *   <li>the cell still holds the generated block ({@code oud}): replaced (so a player-placed block is detected and left alone);</li>
 *   <li>otherwise only what the {@link Beleid} allows: {@code zee} (the islet) air, water and plants; {@code kamp_pad} plants and
 *       leaves, logs only where the generator had a tree, ground only where the generator had ground;</li>
 *   <li>a chunk that was never generated is skipped and reported ("nog niet gegenereerd": it gets the new tiles by itself); no
 *       chunk is ever generated by a patch.</li>
 * </ul>
 * Big stamps run as a {@link Klus} over several server ticks (first a read-only scan chunk by chunk, then the backup of every
 * cell that will change, then {@link #PER_TICK} placements per tick, with progress messages). There is no cell cap for stamps.
 */
public final class WereldStempel {
    private static final Logger LOGGER = LogUtils.getLogger();
    /** Placements (and herstel steps) per server tick: ~76k cells = ~20 ticks = 1 s, no lag spike. */
    public static final int PER_TICK = 4_000;
    /** Cells scanned per tick (reading only; the chunk loads from disk are the cost). */
    static final int SCAN_PER_TICK = 16_000;

    public enum Beleid {
        ZEE, KAMP_PAD;

        static Beleid van(String s) {
            return "kamp_pad".equals(s) ? KAMP_PAD : ZEE;
        }
    }

    /** A stamp: cell i is at pos[3i..3i+2], palet[oud[i]] -> palet[nieuw[i]]; nbt by BlockPos.asLong. */
    public record Stempel(String naam, ResourceKey<Level> dim, String beschrijving, Beleid beleid, @Nullable String gebied, List<BlockState> palet,
                          int[] pos, int[] oud, int[] nieuw, Map<Long, CompoundTag> nbt) {
        public int cellen() {
            return oud.length;
        }

        public BlockPos plek(int i) {
            return new BlockPos(pos[3 * i], pos[3 * i + 1], pos[3 * i + 2]);
        }

        public BlockState oud(int i) {
            return palet.get(oud[i]);
        }

        public BlockState nieuw(int i) {
            return palet.get(nieuw[i]);
        }

        /** The same stamp moved by {@code d} (tests). */
        public Stempel verschoven(BlockPos d, ResourceKey<Level> naar) {
            int[] p = pos.clone();
            for (int i = 0; i < cellen(); i++) {
                p[3 * i] += d.getX();
                p[3 * i + 1] += d.getY();
                p[3 * i + 2] += d.getZ();
            }
            Map<Long, CompoundTag> n = new HashMap<>();
            nbt.forEach((k, v) -> n.put(BlockPos.of(k).offset(d).asLong(), v));
            return new Stempel(naam, naar, beschrijving, beleid, gebied, palet, p, oud, nieuw, n);
        }
    }

    private WereldStempel() {
    }

    // ---- loading ---------------------------------------------------------------------------------------------------------------

    /** Is {@code naam} a registered stamp patch (its json says "soort": "stempel")? */
    public static boolean isStempel(String naam) {
        return WereldPatch.STEMPELS.contains(naam);
    }

    /** The registered stamp {@code naam}, or empty (unknown / unreadable, logged). */
    public static Optional<Stempel> laad(String naam) {
        if (!isStempel(naam)) {
            return Optional.empty();
        }
        String map = "/data/guhs/vadsrijk/patch/";
        try (InputStream in = WereldStempel.class.getResourceAsStream(map + naam + ".json")) {
            if (in == null) {
                LOGGER.warn("[Vadsrijk] stempel {}: json ontbreekt", naam);
                return Optional.empty();
            }
            JsonObject o = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
            try (InputStream b = WereldStempel.class.getResourceAsStream(map + o.get("stempel").getAsString())) {
                if (b == null) {
                    LOGGER.warn("[Vadsrijk] stempel {}: {} ontbreekt", naam, o.get("stempel").getAsString());
                    return Optional.empty();
                }
                return Optional.of(lees(naam, o, NbtIo.readCompressed(b, NbtAccounter.unlimitedHeap())));
            }
        } catch (Exception e) {
            LOGGER.warn("[Vadsrijk] stempel {} niet leesbaar: {}", naam, e.toString());
            return Optional.empty();
        }
    }

    /** json {dimensie, beschrijving, beleid, gebied} + the binary {palet: [state strings], pos, oud, nieuw, nbt: [{pos, nbt}]}. */
    public static Stempel lees(String naam, JsonObject o, CompoundTag t) {
        ResourceKey<Level> dim = ResourceKey.create(Registries.DIMENSION, Identifier.parse(o.get("dimensie").getAsString()));
        List<BlockState> palet = new ArrayList<>();
        ListTag p = t.getListOrEmpty("palet");
        for (int i = 0; i < p.size(); i++) {
            palet.add(WereldPatch.staat(p.getStringOr(i, "minecraft:air")));
        }
        int[] pos = t.getIntArray("pos").orElse(new int[0]);
        int[] oud = t.getIntArray("oud").orElse(new int[0]);
        int[] nieuw = t.getIntArray("nieuw").orElse(new int[0]);
        if (pos.length != 3 * oud.length || nieuw.length != oud.length) {
            throw new IllegalArgumentException("stempel " + naam + ": pos/oud/nieuw passen niet bij elkaar");
        }
        Map<Long, CompoundTag> nbt = new HashMap<>();
        ListTag be = t.getListOrEmpty("nbt");
        for (int i = 0; i < be.size(); i++) {
            CompoundTag c = be.getCompoundOrEmpty(i);
            int[] q = c.getIntArray("pos").orElse(new int[3]);
            nbt.put(BlockPos.asLong(q[0], q[1], q[2]), c.getCompoundOrEmpty("nbt"));
        }
        return new Stempel(naam, dim, o.has("beschrijving") ? o.get("beschrijving").getAsString() : naam,
                Beleid.van(o.has("beleid") ? o.get("beleid").getAsString() : "zee"), o.has("gebied") ? o.get("gebied").getAsString() : null,
                List.copyOf(palet), pos, oud, nieuw, Map.copyOf(nbt));
    }

    // ---- the rules ---------------------------------------------------------------------------------------------------------------

    public enum Oordeel { PLAATS, AL_GOED, BEZET }

    /** What may happen to a cell that now holds {@code nu}, generated as {@code oud}, that the stamp wants as {@code nieuw}. */
    public static Oordeel oordeel(Beleid b, BlockState nu, BlockState oud, BlockState nieuw) {
        if (nu == nieuw) {
            return Oordeel.AL_GOED;
        }
        if (nu.hasBlockEntity()) {
            return Oordeel.BEZET;                         // never a chest, sign, furnace...
        }
        if (nu == oud || nu.isAir() || plant(nu)) {
            return Oordeel.PLAATS;                        // still the generated block, or air / grass / flowers / leaves
        }
        if (b == Beleid.ZEE) {
            return nu.is(Blocks.WATER) || nu.is(Blocks.SEAGRASS) || nu.is(Blocks.TALL_SEAGRASS) || nu.is(Blocks.KELP) || nu.is(Blocks.KELP_PLANT)
                    ? Oordeel.PLAATS : Oordeel.BEZET;
        }
        // kamp_pad: a log only where the generator had a tree, ground only where the generator had ground
        if (nu.is(BlockTags.LOGS) && (oud.is(BlockTags.LOGS) || oud.is(BlockTags.LEAVES))) {
            return Oordeel.PLAATS;
        }
        if (grond(nu) && grond(oud)) {
            return Oordeel.PLAATS;
        }
        return Oordeel.BEZET;
    }

    /** Grass, flowers, ferns, leaves, vines (vanilla's "replaceable by trees" set), fluid-free. */
    static boolean plant(BlockState s) {
        return s.is(BlockTags.REPLACEABLE_BY_TREES) && s.getFluidState().isEmpty();
    }

    static boolean grond(BlockState s) {
        return s.is(Blocks.GRASS_BLOCK) || s.is(Blocks.DIRT) || s.is(Blocks.DIRT_PATH) || s.is(Blocks.COARSE_DIRT) || s.is(Blocks.PODZOL)
                || s.is(Blocks.ROOTED_DIRT) || s.is(Blocks.MOSS_BLOCK) || s.is(BlockTags.DIRT);
    }

    // ---- the job -----------------------------------------------------------------------------------------------------------------

    /** Counts of a (finished) run. */
    public record Uitslag(int cellen, int plaatsen, int alGoed, int bezet, int nietGegenereerd, int chunksNietGegenereerd, @Nullable String backup,
                          @Nullable String fout) {
    }

    /** One run of a stamp over several ticks: {@link #stap} until it returns true. */
    public static final class Klus {
        final ServerLevel level;
        final Stempel s;
        final boolean echt;
        @Nullable final CommandSourceStack bron;
        final int perTick;
        final List<long[]> chunks = new ArrayList<>();          // [chunk key, first cell, end cell)
        int chunk;                                               // scan: next chunk
        final List<Integer> plan = new ArrayList<>();           // cells that will be placed
        final List<BlockState> planOud = new ArrayList<>();
        int geplaatst, alGoed, bezet, nietGegen, chunksNiet, gemeld;
        @Nullable String backup, fout;
        boolean klaar;

        public Klus(ServerLevel level, Stempel s, boolean echt, @Nullable CommandSourceStack bron, int perTick) {
            this.level = level;
            this.s = s;
            this.echt = echt;
            this.bron = bron;
            this.perTick = perTick;
            long vorige = Long.MIN_VALUE;
            for (int i = 0; i < s.cellen(); i++) {                 // (the generator sorts the cells chunk by chunk)
                long k = ChunkPos.pack(s.pos[3 * i] >> 4, s.pos[3 * i + 2] >> 4);
                if (k != vorige || chunks.isEmpty()) {
                    chunks.add(new long[] {k, i, i + 1});
                    vorige = k;
                } else {
                    chunks.get(chunks.size() - 1)[2] = i + 1;
                }
            }
        }

        /** One tick's work; true when the run is done (see {@link #uitslag}). */
        public boolean stap() {
            if (klaar) {
                return true;
            }
            if (chunk < chunks.size()) {
                scan();
                if (chunk < chunks.size()) {
                    return false;
                }
                if (!echt || plan.isEmpty()) {
                    return klaar = true;
                }
                if (!schrijfBackup()) {
                    return klaar = true;
                }
                meld(Component.literal("Stempel " + s.naam + ": backup " + backup + " geschreven, nu " + plan.size() + " blokken plaatsen..."));
                return false;
            }
            int tot = Math.min(plan.size(), geplaatst + perTick);
            for (int j = geplaatst; j < tot; j++) {
                int i = plan.get(j);
                BlockPos b = s.plek(i);
                BlockState nieuw = s.nieuw(i);
                if (level.getBlockState(b) == planOud.get(j)) {     // (unchanged since the scan)
                    level.setBlock(b, nieuw, Block.UPDATE_CLIENTS | Block.UPDATE_KNOWN_SHAPE);
                    CompoundTag nbt = s.nbt.get(b.asLong());
                    if (nbt != null) {
                        BlockEntity be = level.getBlockEntity(b);
                        if (be != null) {
                            be.loadWithComponents(Nbt.input(level.registryAccess(), nbt));
                            be.setChanged();
                            level.sendBlockUpdated(b, nieuw, nieuw, Block.UPDATE_CLIENTS);
                        }
                    }
                }
            }
            geplaatst = tot;
            int procent = plan.isEmpty() ? 100 : geplaatst * 100 / plan.size();
            if (procent / 20 > gemeld && geplaatst < plan.size()) {
                gemeld = procent / 20;
                meld(Component.literal("Stempel " + s.naam + ": " + procent + "% (" + geplaatst + "/" + plan.size() + ")"));
            }
            if (geplaatst >= plan.size()) {
                LOGGER.info("[Vadsrijk] stempel {} toegepast in {}: {} blokken geplaatst, backup data/{}", s.naam, level.dimension().identifier(),
                        plan.size(), backup);
                return klaar = true;
            }
            return false;
        }

        private void scan() {
            NieuwTerrein terrein = NieuwTerrein.van(level);
            int gedaan = 0;
            while (chunk < chunks.size() && gedaan < SCAN_PER_TICK) {
                long[] c = chunks.get(chunk++);
                int cx = ChunkPos.getX(c[0]), cz = ChunkPos.getZ(c[0]);
                int van = (int) c[1], tot = (int) c[2];
                gedaan += tot - van;
                if (!level.hasChunk(cx, cz) && !terrein.bestaat(cx, cz)) {
                    nietGegen += tot - van;                     // never generated: it gets the new tiles itself
                    chunksNiet++;
                    continue;
                }
                level.getChunk(cx, cz);
                for (int i = van; i < tot; i++) {
                    BlockState nu = level.getBlockState(s.plek(i));
                    switch (oordeel(s.beleid, nu, s.oud(i), s.nieuw(i))) {
                        case AL_GOED -> alGoed++;
                        case BEZET -> bezet++;
                        case PLAATS -> {
                            plan.add(i);
                            planOud.add(nu);
                        }
                    }
                }
            }
        }

        private boolean schrijfBackup() {
            String naam = "vr_patch_backup_" + s.naam + "_" + System.currentTimeMillis() + ".nbt";
            try {
                Path map = WereldPatch.map(level.getServer());
                Files.createDirectories(map);
                List<BlockPos> plekken = new ArrayList<>(plan.size());
                List<BlockState> nieuw = new ArrayList<>(plan.size());
                for (int i : plan) {
                    plekken.add(s.plek(i));
                    nieuw.add(s.nieuw(i));
                }
                NbtIo.writeCompressed(backupTag(s.naam, level, plekken, planOud, nieuw), map.resolve(naam));
                backup = naam;
                return true;
            } catch (IOException e) {
                LOGGER.error("[Vadsrijk] stempel {}: backup schrijven mislukt", s.naam, e);
                fout = "backup schrijven mislukt: " + e.getMessage();
                plan.clear();
                return false;
            }
        }

        void meld(Component c) {
            if (bron != null) {
                bron.sendSuccess(() -> c, false);
            }
        }

        public boolean klaar() {
            return klaar;
        }

        public Uitslag uitslag() {
            return new Uitslag(s.cellen(), echt ? (backup == null ? 0 : plan.size()) : plan.size(), alGoed, bezet, nietGegen, chunksNiet, backup, fout);
        }
    }

    /** The whole run at once (tests, small stamps). */
    public static Uitslag toepassen(ServerLevel level, Stempel s, boolean echt) {
        Klus k = new Klus(level, s, echt, null, Integer.MAX_VALUE);
        while (!k.stap()) {
            // (all in this tick)
        }
        return k.uitslag();
    }

    /** The same backup format as {@link WereldPatch} (so {@code patch herstel} undoes a stamp too). */
    static CompoundTag backupTag(String patch, ServerLevel level, List<BlockPos> plekken, List<BlockState> oud, List<BlockState> nieuw) {
        CompoundTag t = new CompoundTag();
        t.putString("patch", patch);
        t.putString("dim", level.dimension().identifier().toString());
        t.putLong("tijd", System.currentTimeMillis());
        Map<BlockState, Integer> index = new LinkedHashMap<>();
        long[] pos = new long[plekken.size()];
        int[] st = new int[plekken.size() * 2];
        for (int i = 0; i < plekken.size(); i++) {
            pos[i] = plekken.get(i).asLong();
            st[2 * i] = index.computeIfAbsent(oud.get(i), x -> index.size());
            st[2 * i + 1] = index.computeIfAbsent(nieuw.get(i), x -> index.size());
        }
        ListTag palet = new ListTag();
        index.keySet().forEach(x -> palet.add(NbtUtils.writeBlockState(x)));
        t.put("palet", palet);
        t.put("plekken", new LongArrayTag(pos));
        t.put("staten", new IntArrayTag(st));
        return t;
    }

    // ---- herstel over several ticks ---------------------------------------------------------------------------------------------

    /** Undo of a (big) backup in steps: the old blocks back where the patch block still stands, last placed first. */
    public static final class HerstelKlus {
        final ServerLevel level;
        final List<BlockState> staten;
        final long[] pos;
        final int[] st;
        final String bestand;
        @Nullable final CommandSourceStack bron;
        int i, terug, over;

        HerstelKlus(ServerLevel level, List<BlockState> staten, long[] pos, int[] st, String bestand, @Nullable CommandSourceStack bron) {
            this.level = level;
            this.staten = staten;
            this.pos = pos;
            this.st = st;
            this.bestand = bestand;
            this.bron = bron;
            this.i = Math.min(pos.length, st.length / 2) - 1;
        }

        boolean stap() {
            int n = 0;
            for (; i >= 0 && n < PER_TICK; i--, n++) {
                BlockPos b = BlockPos.of(pos[i]);
                BlockState oud = staten.get(st[2 * i]), nieuw = staten.get(st[2 * i + 1]);
                if (level.getBlockState(b) == nieuw) {
                    level.setBlock(b, oud, Block.UPDATE_CLIENTS | Block.UPDATE_KNOWN_SHAPE);
                    terug++;
                } else {
                    over++;
                }
            }
            if (i < 0) {
                LOGGER.info("[Vadsrijk] patch-backup {} hersteld: {} teruggezet, {} overgeslagen", bestand, terug, over);
                if (bron != null) {
                    bron.sendSuccess(() -> Component.literal("Hersteld uit " + bestand + ": " + terug + " blokken teruggezet, " + over
                            + " overgeslagen (stonden niet meer zoals de patch ze zette)."), true);
                }
                return true;
            }
            return false;
        }
    }

    /** Starts a stepwise herstel of {@code bestand} (a patch backup in world/data); null = started, else the reason it did not. */
    @Nullable
    public static String herstelInStappen(MinecraftServer server, String bestand, @Nullable CommandSourceStack bron) {
        if (!WereldPatch.BESTAND.matcher(bestand).matches()) {
            return "geen patch-backup: " + bestand;
        }
        Path f = WereldPatch.map(server).resolve(bestand);
        if (!Files.isRegularFile(f)) {
            return "bestand " + f + " bestaat niet";
        }
        CompoundTag t;
        try {
            t = NbtIo.readCompressed(f, NbtAccounter.unlimitedHeap());
        } catch (IOException e) {
            return "lezen mislukt: " + e.getMessage();
        }
        ServerLevel level = server.getLevel(ResourceKey.create(Registries.DIMENSION, Identifier.parse(t.getStringOr("dim", "minecraft:overworld"))));
        if (level == null) {
            return "dimensie " + t.getStringOr("dim", "?") + " bestaat niet";
        }
        ListTag palet = t.getListOrEmpty("palet");
        List<BlockState> staten = new ArrayList<>();
        for (int i = 0; i < palet.size(); i++) {
            staten.add(NbtUtils.readBlockState(BuiltInRegistries.BLOCK, palet.getCompoundOrEmpty(i)));
        }
        HERSTEL.add(new HerstelKlus(level, staten, t.getLongArray("plekken").orElse(new long[0]), t.getIntArray("staten").orElse(new int[0]), bestand, bron));
        return null;
    }

    /** How many cells a backup holds (the command uses the stepwise herstel above {@link #PER_TICK}). */
    static int backupGrootte(MinecraftServer server, String bestand) {
        try {
            CompoundTag t = NbtIo.readCompressed(WereldPatch.map(server).resolve(bestand), NbtAccounter.unlimitedHeap());
            return t.getLongArray("plekken").map(a -> a.length).orElse(0);
        } catch (Exception e) {
            return 0;
        }
    }

    // ---- running jobs -------------------------------------------------------------------------------------------------------------

    static final List<Klus> LOPEND = new CopyOnWriteArrayList<>();
    static final List<HerstelKlus> HERSTEL = new CopyOnWriteArrayList<>();
    /** What each finished command job reports at the end (set by {@link PatchCommando}). */
    static final Map<Klus, java.util.function.Consumer<Uitslag>> AF = new java.util.concurrent.ConcurrentHashMap<>();

    public static void start(Klus k, java.util.function.Consumer<Uitslag> af) {
        AF.put(k, af);
        LOPEND.add(k);
    }

    public static boolean bezig(String naam) {
        return LOPEND.stream().anyMatch(k -> k.s.naam.equals(naam));
    }

    public static void tick(ServerTickEvent.Post e) {
        for (Klus k : LOPEND) {
            boolean klaar;
            try {
                klaar = k.stap();
            } catch (RuntimeException ex) {
                LOGGER.error("[Vadsrijk] stempel {} afgebroken", k.s.naam, ex);
                k.fout = "afgebroken: " + ex;
                k.klaar = true;
                klaar = true;
            }
            if (klaar) {
                LOPEND.remove(k);
                var af = AF.remove(k);
                if (af != null) {
                    af.accept(k.uitslag());
                }
            }
        }
        for (HerstelKlus h : HERSTEL) {
            if (h.stap()) {
                HERSTEL.remove(h);
            }
        }
    }

    /** Server stop: running jobs are dropped (a half-placed stamp: run it again, it continues where it stopped). */
    public static void wis() {
        LOPEND.clear();
        HERSTEL.clear();
        AF.clear();
    }
}
