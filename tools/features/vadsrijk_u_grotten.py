def bestanden():
    gs = grotten()
    java(gs)
    biomen(gs)
    return gs


def build(h):
    gs = bestanden()
    for k, (nl, en) in teksten(gs).items():
        h.lang(k, en, nl)   # (the shared helper takes en first)


def _direct():
    gs = bestanden()
    tk = teksten(gs)
    for taal, i in (("nl_nl", 0), ("en_us", 1)):
        p = os.path.join(A, "assets", "guhs", "lang", f"{taal}.json")
        with open(p, encoding="utf-8") as f:
            regels = f.read().split("\n")
        data = json.loads("\n".join(regels))
        # add-only, line-based (keeps every other line byte-identical: no re-escaping churn)
        nieuw = [(k, v[i]) for k, v in tk.items() if data.get(k) != v[i]]
        bestaand = {k for k, _ in nieuw if k in data}
        uit = []
        for r in regels:
            s = r.strip()
            if s.startswith('"') and '":' in s:
                k = json.loads(s.split('":', 1)[0] + '"')
                if k in bestaand:
                    continue
            uit.append(r)
        # insert before the closing brace
        while uit and uit[-1].strip() == "":
            uit.pop()
        assert uit[-1].strip() == "}"
        uit.pop()
        if nieuw:
            if not uit[-1].rstrip().endswith(","):
                uit[-1] = uit[-1].rstrip() + ","
            for n, (k, v) in enumerate(nieuw):
                uit.append(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}" + ("," if n < len(nieuw) - 1 else ""))
        uit.append("}")
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(uit) + "\n")
        json.loads(open(p, encoding="utf-8").read())
    print(f"vadsrijk_u_grotten: {len(gs)} caves, {len(tk)} texts")


if __name__ == "__main__":
    _direct()
