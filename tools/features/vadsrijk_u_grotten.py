def _schrijf(pad, obj):
    os.makedirs(os.path.dirname(pad), exist_ok=True)
    with open(pad, "w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)
        f.write("\n")


def grotten():
    import grot
    import grotplan
    uit = []
    for g in grot.grotten():
        g.bouw()
        meta = grotplan.META[g.id]
        F = g.F
        import numpy as np
        ii, jj = np.nonzero(~np.isnan(F))
        x0, x1 = int(ii.min()) + g.x0 - 1, int(ii.max()) + g.x0 + 1
        z0, z1 = int(jj.min()) + g.z0 - 1, int(jj.max()) + g.z0 + 1
        y0 = int(math.ceil(np.nanmin(F))) - 2
        y1 = int(np.max(g.C[~np.isnan(F)])) + 1
        for t in g.trappen:
            x0, x1 = min(x0, int(t["cx"]) - 4), max(x1, int(t["cx"]) + 4)
            z0, z1 = min(z0, int(t["cz"]) - 4), max(z1, int(t["cz"]) + 4)
            # (the shaft above the cave ceiling is not "in the cave": the box stops at the highest room ceiling)
        uit.append(dict(id=g.id, zone=g.zone, doos=(x0, y0, z0, x1, y1, z1), meta=meta, plekken=g.plekken))
    return uit


def java(gs):
    def bp(v):
        return f"new BlockPos({int(v[0])}, {int(v[1])}, {int(v[2])})"
    regels, amb = [], []
    for d in gs:
        m = d["meta"]
        x0, y0, z0, x1, y1, z1 = d["doos"]
        pl = ",\n".join(f'                    Map.entry("{k}", {bp(v)})' for k, v in d["plekken"].items())
        regels.append(f'            new Grot("{d["id"]}", {d["zone"]}, {x0}, {y0}, {z0}, {x1}, {y1}, {z1}, {m["lv"][0]}, {m["lv"][1]}, {m["elite"]}, '
                      f'"{m["biome"]}", Map.ofEntries(\n{pl}))')
        for (k, a, tier, n, r, zoek) in m["amb"]:
            amb.append(f'            new Amb("{d["id"]}", "grot_{d["id"]}_{k}", {d["zone"]}, "{a}", {tier}, {n}, {r}, "{zoek}")')
    src = f"""package nl.juiced.guhs.feature.vadsrijk.grotten;

import java.util.List;
import java.util.Map;

import net.minecraft.core.BlockPos;

/**
 * GENERATED by tools/features/vadsrijk_u_grotten.py from tools/vadsrijk/grotten/grotplan.py (do not edit by hand). The five
 * atmosphere caves of Het Vadsrijk (U-GROTTEN): area box (world, y included), levels, the elite's level, the biome id and every
 * POI (stand positions; {{@code puzzel}} = the puzzle anchor at floor - 4, {{@code amb_*}} = Ambacht anchors at floor - 3).
 */
public final class GrotData {{
    public record Grot(String id, int zone, int minX, int minY, int minZ, int maxX, int maxY, int maxZ, int minLv, int maxLv, int eliteLv,
            String biome, Map<String, BlockPos> plekken) {{
        public boolean bevat(double x, double y, double z) {{
            return x >= minX && x < maxX + 1 && z >= minZ && z < maxZ + 1 && y >= minY && y < maxY + 1;
        }}

        public BlockPos plek(String k) {{
            return plekken.get(k);
        }}
    }}

    /** An Ambacht spot group in a cave: the POI id (grot_&lt;cave&gt;_amb_n), Ambacht / Zoek enum names. */
    public record Amb(String grot, String poi, int zone, String ambacht, int tier, int aantal, int straal, String zoek) {{
    }}

    public static final List<Grot> ALLE = List.of(
{(","+chr(10)).join(regels)});

    public static final List<Amb> AMBACHT = List.of(
{(","+chr(10)).join(amb)});

    private GrotData() {{
    }}
}}
"""
    os.makedirs(os.path.dirname(JAVA), exist_ok=True)
    with open(JAVA, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)


