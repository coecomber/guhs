"""
U-GROTTEN (round U, FEEDBACK_RONDE4 V2): one hand-made atmosphere cave per zone of Het Vadsrijk.

The caves themselves are built into the map tiles by tools/vadsrijk/grotten (grot.py = engine, grotplan.py = the five caves),
hooked into every zone's map maker. This generator writes the game side:
  - src/main/java/.../vadsrijk/grotten/GrotData.java (GENERATED): per cave its area box (with y range), levels, biome id and
    every POI (stand positions), plus the Ambacht spot groups;
  - data/guhs/worldgen/biome/vadsrijk_grot_<id>.json (one biome per cave: "Het Vadsrijk - <grot>" in F3 / JourneyMap);
  - lang (nl + en): area names, biome names, the discovery card, the book category, treasure + elite texts, dev commands.

Standalone (from the project root): PYTHONPATH="tools;tools/features" python tools/features/vadsrijk_u_grotten.py
"""
