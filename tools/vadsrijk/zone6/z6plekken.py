"""X-KAART: the zone-6 spots exactly as the GAME uses them, for the checkers (poicheck6, loopcheck6, fundering).

The game reads Z6WereldPlekken.ALLE (generated by poi6.py, snapped onto the real blocks). The json cache
(_cache/plekken_z6.json) can be stale (another worktree, an older regen) or absent, so the checkers read the Java first and
fall back to the cache only when the Java is missing.
    lees() -> {id: [x, y, z]}
"""
import json
import os
import re

HIER = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HIER, "..", "..", ".."))
JAVA = os.path.join(ROOT, "src", "main", "java", "nl", "juiced", "guhs", "feature", "vadsrijk", "zone6", "wereld",
                    "Z6WereldPlekken.java")
CACHE = os.path.join(HIER, "..", "_cache", "plekken_z6.json")
_RE = re.compile(r'Map\.entry\("([^"]+)",\s*new BlockPos\((-?\d+),\s*(-?\d+),\s*(-?\d+)\)\)')


def lees(bron=None):
    """id -> [x, y, z] from Z6WereldPlekken.java (ALLE), else from the json cache. bron: 'java' / 'json' / None (auto)."""
    if bron != "json" and os.path.exists(JAVA):
        with open(JAVA, encoding="utf-8") as f:
            uit = {m[0]: [int(m[1]), int(m[2]), int(m[3])] for m in _RE.findall(f.read())}
        if uit:
            return uit
    with open(CACHE, encoding="utf-8") as f:
        return json.load(f)


def bron_naam():
    return "Z6WereldPlekken.java" if os.path.exists(JAVA) else "_cache/plekken_z6.json"
