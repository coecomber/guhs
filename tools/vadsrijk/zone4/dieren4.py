"""[T-Z4DIEREN] Positions for the moving things of zone 4: writes Z4DierenPlekken.java (GENERATED, never commit).

  * the guh kites: every kite the map kit flies (kit/bouwsels.VLIEGERS: anchor, kite centre, size, colours), recorded by
    building Lampionhaven + the Vliegereiland in this process (the tiles no longer hold the wool kites, see bouwsels);
  * Ouwe Dobber's swim path: control points of a closed loop (Catmull-Rom in Java, DobberRoute): it waits at his own halte
    next to the Schildpadeiland jetty (boot_dok_schildpad), then swims SCHILDPAD_ROUTE points 4..20 (the points near the
    static island are left out: the island sits ON the plan's loop). Every point of the spline is checked: the turtle
    (radius 6) never touches the static island (shell + head + flippers), the jetty, or water shallower than 3.

Called from maak4.maak (after the tiles); standalone from the project root: python tools/vadsrijk/zone4/dieren4.py
"""
import math
import os
import sys

HIER = os.path.dirname(os.path.abspath(__file__))
if HIER not in sys.path:
    sys.path.insert(0, HIER)
    sys.path.insert(1, os.path.join(HIER, "kit"))
    sys.path.append(os.path.join(HIER, "..", "wereld"))
ROOT = os.path.abspath(os.path.join(HIER, "..", "..", ".."))
UIT = os.path.join(ROOT, "src", "main", "java", "nl", "juiced", "guhs", "feature", "vadsrijk", "zone4", "dieren", "Z4DierenPlekken.java")

import plan4 as PL  # noqa: E402

HALTE_V, HALTE_U = 33, 4        # the halte in the static island's frame (v = towards the loop centre, the jetty side)
ROUTE_VAN, ROUTE_TOT = 4, 20     # SCHILDPAD_ROUTE points swum after the halte
STRAAL = 6                       # the turtle's half width (shell 11 wide) for the clearance check


def vliegers():
    import bouwsels as BW
    import haven as HV
    import eilanden as EI
    BW.VLIEGERS.clear()
    HV._P = None                     # (maak4 may have built them already in this process: build again to record the kites)
    EI._CACHE.pop("vlieger", None)
    HV._plek(False)
    EI.plek("vlieger", False)
    uit, gezien = [], set()
    for v in BW.VLIEGERS:
        sleutel = (v[1][0], v[1][1], v[1][2])
        if sleutel in gezien:
            continue
        gezien.add(sleutel)
        uit.append(v)
    return uit


def route():
    x0, z0, fx, fz = PL.schildpad_assen()
    lok = PL.schildpad_lok
    R = PL.schildpad_route()
    punten = [lok(HALTE_U - 10, HALTE_V), lok(HALTE_U, HALTE_V), lok(HALTE_U + 10, HALTE_V)] + [tuple(map(float, p)) for p in R[ROUTE_VAN:ROUTE_TOT + 1]]
    return [(round(x, 1), round(z, 1)) for x, z in punten]


def _spline(P, n=16):
    def cr(p0, p1, p2, p3, t):
        return tuple(0.5 * ((2 * p1[i]) + (-p0[i] + p2[i]) * t + (2 * p0[i] - 5 * p1[i] + 4 * p2[i] - p3[i]) * t * t
                            + (-p0[i] + 3 * p1[i] - 3 * p2[i] + p3[i]) * t ** 3) for i in range(2))
    out = []
    for i in range(len(P)):
        for s in range(n):
            out.append(cr(P[i - 1], P[i], P[(i + 1) % len(P)], P[(i + 2) % len(P)], s / n))
    return out


def controleer(P):
    """Spots on the path where the turtle would touch the static island, its jetty or shallow ground (empty = fine)."""
    x0, z0, fx, fz = PL.schildpad_assen()
    dok = PL.plekken().get("boot_dok_schildpad")
    fout = []
    for (x, z) in _spline(P, 8):
        for dx in range(-STRAAL, STRAAL + 1):
            for dz in range(-STRAAL, STRAAL + 1):
                if dx * dx + dz * dz > STRAAL * STRAAL:
                    continue
                X, Z = x + dx, z + dz
                u = (X - x0) * fx + (Z - z0) * fz
                v = -(X - x0) * fz + (Z - z0) * fx
                eiland = (u / 26) ** 2 + (v / 27) ** 2 <= 1 or (abs(v) < 8 and -30 < u < 38)
                steiger = dok is not None and abs(X - dok[0]) <= 0.5 and abs(Z - dok[2]) <= 1.5
                if eiland or steiger or PL.y_grond(int(X), int(Z)) > PL.ZEE - 3:
                    fout.append((int(x), int(z)))
                    break
            else:
                continue
            break
    return fout


def schrijf():
    vl = vliegers()
    P = route()
    fout = controleer(P)
    if fout:
        print("dieren4: LET OP, Ouwe Dobber raakt iets op", fout[:8])
    dok = PL.plekken()["boot_dok_schildpad"]
    lengte = sum(math.dist(a, b) for a, b in zip(_spline(P), _spline(P)[1:] + _spline(P)[:1]))
    rij = ",\n            ".join(
        f"new Vlieger({a[0]}, {a[1]}, {a[2]}, {p[0]}, {p[1]}, {p[2]}, {g}f, 0x{k[0]:02X}{k[1]:02X}{k[2]:02X}, 0x{k2[0]:02X}{k2[1]:02X}{k2[2]:02X})"
        for (a, p, g, k, k2) in vl)
    punten = ", ".join("{" + f"{x}, {z}" + "}" for x, z in P)
    src = f"""package nl.juiced.guhs.feature.vadsrijk.zone4.dieren;

import java.util.List;

/**
 * GENERATED by tools/vadsrijk/zone4/dieren4.py (via maak_kaart.py --zone 4; do not edit by hand, do not commit).
 * The guh kites of zone 4 (from the map kit, the tiles no longer hold them) and Ouwe Dobber's swim path.
 */
public final class Z4DierenPlekken {{
    /** A kite: the anchor (where its string is tied, on the ground), the kite's centre, its size and two colours (rgb). */
    public record Vlieger(double ax, double ay, double az, double x, double y, double z, float grootte, int kleur, int kleur2) {{
    }}

    public static final List<Vlieger> VLIEGERS = List.of(
            {rij});

    /** Ouwe Dobber's loop (x, z control points, closed, Catmull-Rom): point 1 is his halte by the jetty. */
    public static final double[][] DOBBER_ROUTE = {{{punten}}};
    public static final int DOBBER_HALTE = 1;
    /** Where you step off at the halte: the end of the Schildpadeiland jetty (stand y). */
    public static final int DOK_X = {dok[0]}, DOK_Y = {dok[1]}, DOK_Z = {dok[2]};
    /** Length of the loop (blocks, from the generator; DobberRoute measures its own). */
    public static final double LENGTE = {lengte:.1f};
    /** Spots where the check found the turtle touching the island/jetty/shallows (0 = fine). */
    public static final int CHECK_FOUTEN = {len(fout)};

    private Z4DierenPlekken() {{
    }}
}}
"""
    os.makedirs(os.path.dirname(UIT), exist_ok=True)
    with open(UIT, "w", encoding="utf-8", newline="\n") as f:
        f.write(src)
    print(f"zone 4 dieren: {len(vl)} vliegers, schildpadroute {len(P)} punten ({lengte:.0f} blokken), {len(fout)} botsingen")
    return len(fout)


if __name__ == "__main__":
    sys.exit(1 if schrijf() else 0)
