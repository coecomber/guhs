def plat(prefix, o, uit):
    if isinstance(o, list) and len(o) == 3 and all(isinstance(v, int) for v in o):
        uit[prefix] = o
    elif isinstance(o, dict):
        for k, v in o.items():
            plat(f"{prefix}.{k}" if prefix else k, v, uit)


def bp(v):
    return f"new BlockPos({v[0]}, {v[1]}, {v[2]})"


def gebied_java(g, rec):
    i, vorm, p, y0, y1, lo, hi = g[:7]
    extra = f", {str(g[7]).lower()}" if len(g) > 7 else ""
    if vorm == "doos":
        return f'            {rec}.doos("{i}", {p[0]}, {p[1]}, {p[2]}, {p[3]}, {y0}, {y1}, {lo}, {hi}{extra})'
    return f'            {rec}.cilinder("{i}", {p[0]}, {p[1]}, {p[2]}, {p[3]}, {y0}, {y1}, {lo}, {hi}{extra})'


def leven_java(leven):
    """Extra lists for the life/atmosphere code (particles, NPC placement): chimneys, beehives, lantern strings."""
    uit = []
    uitleg = {"SCHOORSTENEN": "Chimney tops (smoke particles: code side; never a campfire there, a campfire is a checkpoint).",
              "BIJENKORVEN": "Beehives / bee spots (bee-swarm particles: code side).",
              "LICHTJES": "Lantern strings, glowing windows and lampion posts worth a soft glow / firefly at night.",
              "BRUGGEN": "The middle of bridges and boardwalks (guhs walking/standing on bridges: npc side)."}
    for k, v in leven.items():
        uit.append(f"    /** {uitleg.get(k, k)} */")
        uit.append(f"    public static final List<BlockPos> {k} = List.of(")
        uit.append((","+chr(10)).join("            " + bp(p) for p in v) + ");")
        uit.append("")
    return chr(10).join(uit)


