"""Global block palette for the map tiles: state strings <-> ids, 26.1 name fixes, validation and the opaque set.

State strings look like "ns:name[k=v,...]" (no namespace = guhs). Id 0 = air (never written). Id 1 = CARVE: a stamp that
writes "minecraft:cave_air" (or CARVE) clears what was there (terrain) and also leaves air.
"""
import os
import zipfile

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
GUHS_BS = os.path.join(ROOT, "src", "main", "resources", "assets", "guhs", "blockstates")
CLIENT_JAR = os.path.join(os.environ.get("APPDATA", ""), "PrismLauncher", "libraries", "com", "mojang", "minecraft",
                          "26.1.2", "minecraft-26.1.2-client.jar")

CARVE = "minecraft:cave_air"
HERNOEM = {"minecraft:chain": "minecraft:iron_chain", "minecraft:grass": "minecraft:short_grass"}
# blocks of this slice that the generator uses before their assets exist (they are generated by vadsrijk_wereld.py)
EIGEN = {"guhs:vr_w_litteken_gras", "guhs:vr_w_litteken_plant", "guhs:vr_w_portaal", "guhs:vr_w_poortsteen",
         "guhs:vr_w_deurblok", "guhs:vr_w_lichtstraal"}


def norm(s):
    if ":" not in s.split("[")[0]:
        s = "guhs:" + s
    naam, _, rest = s.partition("[")
    naam = HERNOEM.get(naam, naam)
    props = {}
    if rest:
        for kv in rest.rstrip("]").split(","):
            if kv:
                k, v = kv.split("=")
                props[k] = v
    if naam.endswith("_leaves") or naam in ("guhs:wolkjeshout_bladeren", "guhs:wolkjeshout_bladeren_roze"):
        props["persistent"] = "true"
        props.setdefault("distance", "7")
        props.setdefault("waterlogged", "false")
    if props:
        return naam + "[" + ",".join(f"{k}={props[k]}" for k in sorted(props)) + "]"
    return naam


def splits(s):
    naam, _, rest = s.partition("[")
    props = {}
    if rest:
        for kv in rest.rstrip("]").split(","):
            k, v = kv.split("=")
            props[k] = v
    return naam, props


class Palet:
    def __init__(self):
        self.lijst = ["minecraft:air", CARVE]
        self.idx = {"minecraft:air": 0, CARVE: 1}

    def id(self, s):
        i = self.idx.get(s)
        if i is not None:
            return i
        n = norm(s)
        i = self.idx.get(n)
        if i is None:
            i = len(self.lijst)
            self.lijst.append(n)
            self.idx[n] = i
        self.idx[s] = i
        return i

    def lut(self, scene_pal):
        """Lookup array: scene palette index -> global id."""
        return np.array([0 if s == "minecraft:air" else self.id(s) for s in scene_pal], np.uint16)


_mc = None


def bestaat(naam):
    global _mc
    if _mc is None:
        _mc = set()
        with zipfile.ZipFile(CLIENT_JAR) as z:
            for n in z.namelist():
                if n.startswith("assets/minecraft/blockstates/") and n.endswith(".json"):
                    _mc.add("minecraft:" + n.rsplit("/", 1)[1][:-5])
        _mc |= {"minecraft:air", "minecraft:cave_air", "minecraft:void_air", "minecraft:barrier", "minecraft:light",
                "minecraft:structure_void"}
    if naam.startswith("minecraft:"):
        return naam in _mc
    if naam in EIGEN:
        return True
    return os.path.exists(os.path.join(GUHS_BS, naam.split(":", 1)[1] + ".json"))


def controleer(palet):
    mis = sorted({splits(s)[0] for s in palet.lijst if not bestaat(splits(s)[0])})
    return mis
